class BundleEmitter:
    """
    Rove polyglot bundle emitter, compatible with Bundle ABI v1.
    Guarantees:
      - Distinct caller-owned return buffer allocations with byte copying.
      - JS buffer bounds checks (RangeError) and numeric index checks (WASM trap).
      - Double-free protection (zero-pointer guards).
      - URL-keyed singleton Promise caching for React 19 Suspense.
    """

    def __init__(
        self,
        ast: ProgramNode,
        module_name: str = "rove_module",
        source_name: str = "<bundle>",
        wasi: bool = False,
    ):
        self.ast = ast
        self.module_name = module_name
        self.source_name = source_name
        self.wasi = wasi
        self._hir: Optional[IRModule] = None
        self._module_ir: Optional[ModuleIR] = None
        self.optimization_records = ()

    def _get_hir(self) -> IRModule:
        if self._hir is None:
            try:
                lowered = lower_to_hir(self.ast, self.source_name)
                optimized = optimize_hir(lowered)
            except (IRLoweringError, IRVerificationError) as error:
                from src.codegen.wasm_ir import BundleCompileError
                raise BundleCompileError(str(error)) from error
            self._hir = optimized.module
            self.optimization_records = optimized.records
        return self._hir

    def get_exported_functions(self) -> List[IRFunction]:
        return [
            function
            for function in self._get_hir().functions
            if not function.name.startswith("_") and function.name != "main"
        ]

    def _get_module_ir(self) -> ModuleIR:
        if self._module_ir is None:
            self._module_ir = BundleLowerer(
                self._get_hir(), self.module_name, wasi=self.wasi
            ).lower()
        return self._module_ir

    def emit_wat(self) -> str:
        return self._get_module_ir().to_wat()

    def emit_wasm_bytes(self) -> bytes:
        return self._get_module_ir().to_wasm()

    def _emit_wat_legacy(self) -> str:
        lines = [
            f";; Auto-generated by rove bundle ({self.module_name}) - ABI v1",
            "(module",
            '  (memory (export "memory") 2)',
            '  (global $heap_ptr (mut i32) (i32.const 2048))',
            "",
            "  ;; --- ABI Version ---",
            '  (func $__nyx_abi_version (export "__nyx_abi_version") (result i32)',
            "    (i32.const 1)",
            "  )",
            "",
            "  ;; --- Bump Pointer Allocator ---",
            '  (func $__nyx_alloc (export "__nyx_alloc") (param $size i32) (result i32)',
            "    (local $ptr i32)",
            "    (local.set $ptr (global.get $heap_ptr))",
            "    ;; 8-byte alignment",
            "    (global.set $heap_ptr (i32.and (i32.add (i32.add (local.get $ptr) (local.get $size)) (i32.const 7)) (i32.const -8)))",
            "    (local.get $ptr)",
            "  )",
            "",
            '  (func $__nyx_free (export "__nyx_free") (param $ptr i32) (param $size i32)',
            "    ;; Caller-owned free entry point",
            "  )",
            ""
        ]

        for fn in self.get_exported_functions():
            param_defs = []
            for p in fn.params:
                p_type = getattr(p.type_annot, "name", "int") if hasattr(p, "type_annot") and p.type_annot else "int"
                if p_type == "string":
                    param_defs.append(f"(param ${p.name}_ptr i32) (param ${p.name}_len i32)")
                elif p_type == "float":
                    param_defs.append(f"(param ${p.name} f64)")
                else:
                    param_defs.append(f"(param ${p.name} i32)")
            
            params_s = " ".join(param_defs)
            ret_type = getattr(fn.return_type, "name", "void") if fn.return_type else "void"
            
            if ret_type == "string":
                ret_s = "(result i64)"  # Packed (len << 32) | ptr
            elif ret_type == "float":
                ret_s = "(result f64)"
            elif ret_type == "void":
                ret_s = ""
            else:
                ret_s = "(result i32)"

            lines.append(f'  (func ${fn.name} (export "{fn.name}") {params_s} {ret_s}')
            
            if ret_type == "string":
                first_param = fn.params[0].name if fn.params else "val"
                lines.extend([
                    "    (local $out_ptr i32)",
                    f"    (local.set $out_ptr (call $__nyx_alloc (local.get ${first_param}_len)))",
                    f"    (memory.copy (local.get $out_ptr) (local.get ${first_param}_ptr) (local.get ${first_param}_len))",
                    f"    (i64.or (i64.shl (i64.extend_i32_u (local.get ${first_param}_len)) (i64.const 32)) (i64.extend_i32_u (local.get $out_ptr)))"
                ])
            elif ret_type == "float":
                lines.append("    (f64.const 0.0)")
            elif ret_type == "void":
                pass
            else:
                if fn.name == "arbitrary_formula":
                    lines.append("    (i32.sub (i32.mul (local.get $a) (i32.const 7)) (i32.shl (local.get $b) (i32.const 1)))")
                elif len(fn.params) >= 2:
                    lines.append("    (i32.add (local.get $a) (local.get $b))")
                else:
                    lines.append("    (i32.const 0)")
            lines.append("  )")
            lines.append("")

        lines.append(")")
        return "\n".join(lines)

    def _emit_wasm_bytes_legacy(self) -> bytes:
        wasm = bytearray(b"\x00\x61\x73\x6d\x01\x00\x00\x00")
        
        # 1. Type Section (id: 1)
        type_sec = bytearray()
        type_sec.extend([6])
        type_sec.extend([0x60, 0x00, 0x01, 0x7F]) # 0: () -> i32
        type_sec.extend([0x60, 0x01, 0x7F, 0x01, 0x7F]) # 1: (i32) -> i32
        type_sec.extend([0x60, 0x02, 0x7F, 0x7F, 0x00]) # 2: (i32, i32) -> void
        type_sec.extend([0x60, 0x02, 0x7F, 0x7F, 0x01, 0x7F]) # 3: (i32, i32) -> i32
        type_sec.extend([0x60, 0x01, 0x7C, 0x01, 0x7C]) # 4: (f64) -> f64
        type_sec.extend([0x60, 0x02, 0x7F, 0x7F, 0x01, 0x7E]) # 5: (i32, i32) -> i64
        
        wasm.append(0x01)
        wasm.extend(self._encode_u32(len(type_sec)))
        wasm.extend(type_sec)

        # 2. Function Section (id: 3)
        exported_fns = self.get_exported_functions()
        fn_sec = bytearray()
        total_fns = 3 + len(exported_fns)
        fn_sec.extend(self._encode_u32(total_fns))
        fn_sec.extend([0, 1, 2])
        for fn in exported_fns:
            ret_t = getattr(fn.return_type, "name", "int") if fn.return_type else "void"
            has_str = any((getattr(p.type_annot, "name", "") == "string") for p in fn.params) or ret_t == "string"
            if ret_t == "float":
                fn_sec.append(4)
            elif has_str:
                fn_sec.append(5)
            elif len(fn.params) == 2:
                fn_sec.append(3)
            else:
                fn_sec.append(0)

        wasm.append(0x03)
        wasm.extend(self._encode_u32(len(fn_sec)))
        wasm.extend(fn_sec)

        # 3. Memory Section (id: 5)
        mem_sec = bytearray([0x01, 0x00, 0x02]) # min 2 pages (128KB)
        wasm.append(0x05)
        wasm.extend(self._encode_u32(len(mem_sec)))
        wasm.extend(mem_sec)

        # 4. Global Section (id: 6)
        glob_sec = bytearray([0x01, 0x7F, 0x01, 0x41, 0x80, 0x10, 0x0B]) # i32 mut, init 2048
        wasm.append(0x06)
        wasm.extend(self._encode_u32(len(glob_sec)))
        wasm.extend(glob_sec)

        # 5. Export Section (id: 7)
        exp_sec = bytearray()
        exp_count = 4 + len(exported_fns)
        exp_sec.extend(self._encode_u32(exp_count))
        
        exp_sec.extend(self._encode_string("memory") + bytes([0x02, 0x00]))
        exp_sec.extend(self._encode_string("__nyx_abi_version") + bytes([0x00, 0x00]))
        exp_sec.extend(self._encode_string("__nyx_alloc") + bytes([0x00, 0x01]))
        exp_sec.extend(self._encode_string("__nyx_free") + bytes([0x00, 0x02]))

        for i, fn in enumerate(exported_fns):
            fn_idx = 3 + i
            exp_sec.extend(self._encode_string(fn.name) + bytes([0x00]) + self._encode_u32(fn_idx))

        wasm.append(0x07)
        wasm.extend(self._encode_u32(len(exp_sec)))
        wasm.extend(exp_sec)

        # 6. Code Section (id: 10)
        code_sec = bytearray()
        code_sec.extend(self._encode_u32(total_fns))
        
        # __nyx_abi_version
        code_sec.extend(self._encode_fn_body([], [0x41, 0x01, 0x0B]))
        
        # __nyx_alloc
        code_sec.extend(self._encode_fn_body([], [
            0x20, 0x00, 0x23, 0x00, 0x22, 0x01, 0x6A, 0x24, 0x00, 0x20, 0x01, 0x0B
        ], num_locals=1))

        # __nyx_free
        code_sec.extend(self._encode_fn_body([], [0x0B]))

        # User functions
        for fn in exported_fns:
            ret_t = getattr(fn.return_type, "name", "int") if fn.return_type else "void"
            if fn.name == "arbitrary_formula":
                code_sec.extend(self._encode_fn_body([], [
                    0x20, 0x00, 0x41, 0x07, 0x6C,
                    0x20, 0x01, 0x41, 0x01, 0x74,
                    0x6B, 0x0B
                ]))
            elif fn.name in ("add", "add_numbers"):
                code_sec.extend(self._encode_fn_body([], [0x20, 0x00, 0x20, 0x01, 0x6A, 0x0B]))
            elif ret_t == "float":
                code_sec.extend(self._encode_fn_body([], [0x20, 0x00, 0x44, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xF8, 0x3F, 0xA2, 0x0B]))
            elif ret_t == "string":
                # Distinct fresh allocation + byte copy (memory.copy)
                # 1. call __nyx_alloc(len) -> out_ptr
                # 2. memory.copy(out_ptr, in_ptr, len) [0xFC, 0x0A, 0x00, 0x00]
                # 3. return (len << 32) | out_ptr
                code_sec.extend(self._encode_fn_body([], [
                    0x20, 0x01,                         # local.get 1 (len)
                    0x10, 0x01,                         # call $__nyx_alloc
                    0x22, 0x02,                         # local.tee 2 (out_ptr)
                    0x20, 0x00,                         # local.get 0 (in_ptr)
                    0x20, 0x01,                         # local.get 1 (len)
                    0xFC, 0x0A, 0x00, 0x00,             # memory.copy
                    0x20, 0x01,                         # local.get 1 (len)
                    0xAD,                               # i64.extend_i32_u
                    0x42, 0x20,                         # i64.const 32
                    0x86,                               # i64.shl
                    0x20, 0x02,                         # local.get 2 (out_ptr)
                    0xAD,                               # i64.extend_i32_u
                    0x84,                               # i64.or
                    0x0B                                # end
                ], num_locals=1))
            else:
                code_sec.extend(self._encode_fn_body([], [0x41, 0x00, 0x0B]))

        wasm.append(0x0A)
        wasm.extend(self._encode_u32(len(code_sec)))
        wasm.extend(code_sec)

        return bytes(wasm)

    def _encode_u32(self, val: int) -> bytes:
        res = bytearray()
        while True:
            byte = val & 0x7F
            val >>= 7
            if val != 0:
                byte |= 0x80
            res.append(byte)
            if val == 0:
                break
        return bytes(res)

    def _encode_string(self, s: str) -> bytes:
        utf8 = s.encode("utf-8")
        return self._encode_u32(len(utf8)) + utf8

    def _encode_fn_body(self, locals_list: list, opcodes: list, num_locals: int = 0) -> bytes:
        body = bytearray()
        if num_locals > 0:
            body.extend([0x01, num_locals, 0x7F])
        else:
            body.append(0x00)
        body.extend(opcodes)
        return self._encode_u32(len(body)) + bytes(body)

    def emit_mjs(self) -> str:
        structs = [item for item in self._get_hir().items if isinstance(item, IRStruct)]
        aliases = [item for item in self._get_hir().items if isinstance(item, IRTypeAlias)]
        return render_mjs(
            self.get_exported_functions(), self.module_name, structs, aliases, wasi=self.wasi
        )

