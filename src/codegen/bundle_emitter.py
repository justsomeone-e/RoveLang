    def emit_package_json(
        self,
        include_react: bool = False,
        include_vue: bool = False,
        include_svelte: bool = False,
    ) -> str:
        package_name = re.sub(r"[^a-z0-9._-]+", "-", self.module_name.lower()).strip("-._")
        if not package_name:
            package_name = "rove-wasm-module"
        exports: Dict[str, Any] = {
            ".": {
                "types": f"./{self.module_name}.d.ts",
                "import": f"./{self.module_name}.mjs",
                "default": f"./{self.module_name}.mjs",
            }
        }
        files = [
            f"{self.module_name}.wasm",
            f"{self.module_name}.mjs",
            f"{self.module_name}.d.ts",
        ]
        manifest: Dict[str, Any] = {
            "name": package_name,
            "version": "0.0.0",
            "private": True,
            "type": "module",
            "types": f"./{self.module_name}.d.ts",
            "exports": exports,
            "files": files,
            "sideEffects": False,
            "rove": {"abi": 1, "hostAbi": 1, "target": "wasm32"},
            "nyx": {"abi": 1, "hostAbi": 1, "target": "wasm32"},
        }
        if include_react:
            exports["./react"] = {
                "types": f"./{self.module_name}.react.d.ts",
                "import": f"./{self.module_name}.react.mjs",
                "default": f"./{self.module_name}.react.mjs",
            }
            files.extend([
                f"{self.module_name}.react.mjs",
                f"{self.module_name}.react.d.ts",
            ])
            manifest["peerDependencies"] = {"react": ">=19.0.0 <20"}
        if include_vue:
            exports["./vue"] = {
                "types": f"./{self.module_name}.vue.d.ts",
                "import": f"./{self.module_name}.vue.mjs",
                "default": f"./{self.module_name}.vue.mjs",
            }
            files.extend([f"{self.module_name}.vue.mjs", f"{self.module_name}.vue.d.ts"])
            manifest.setdefault("peerDependencies", {})["vue"] = ">=3.4.0 <4"
        if include_svelte:
            exports["./svelte"] = {
                "types": f"./{self.module_name}.svelte.d.ts",
                "import": f"./{self.module_name}.svelte.mjs",
                "default": f"./{self.module_name}.svelte.mjs",
            }
            files.extend([f"{self.module_name}.svelte.mjs", f"{self.module_name}.svelte.d.ts"])
            manifest.setdefault("peerDependencies", {})["svelte"] = ">=5.0.0 <6"
        return json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
