def _is_known(value_type: IRType) -> bool:
    if value_type.is_unknown or value_type.name == "null":
        return False
    if value_type.arguments and not all(_is_known(argument) for argument in value_type.arguments):
        return False
    if value_type.is_function:
        return all(_is_known(parameter) for parameter in value_type.parameter_types) and _is_known(
            value_type.return_type or VOID
        )
    return True


def _strip_optional(value_type: IRType) -> IRType:
    return value_type.with_optional(False) if value_type.optional else value_type


def _merge_types(current: IRType, candidate: IRType) -> IRType:
    if not _is_known(candidate):
        return current
    if not _is_known(current):
        return candidate
    if current == candidate:
        return current
    left = _strip_optional(current)
    right = _strip_optional(candidate)
    if left == right:
        return left.with_optional(current.optional or candidate.optional)
    if left.is_numeric and right.is_numeric:
        return FLOAT.with_optional(current.optional or candidate.optional)
    return current


class ModuleTypeInference:
    """Resolve HIR ``any`` slots from whole-module value-flow constraints."""

    def __init__(self, module: IRModule):
        self.module = module
        self.symbol_types: Dict[str, IRType] = {}
        self.function_returns: Dict[str, IRType] = {}
        self.functions: Dict[str, IRFunction] = {}
        self.structs: Dict[str, IRStruct] = {}
        self.struct_fields: Dict[Tuple[str, str], IRType] = {}
        self.methods: Dict[Tuple[str, str], IRFunction] = {}
        self.method_owner: Dict[str, str] = {}
        self.changed = False
        self._register()
        for _ in range(32):
            self.changed = False
            self._scan_module()
            if not self.changed:
                break

    def _register(self) -> None:
        for item in self.module.items:
            if isinstance(item, IRFunction):
                self.functions[item.symbol] = item
                self.function_returns[item.symbol] = item.return_type
                for parameter in item.params:
                    self.symbol_types[parameter.symbol] = parameter.type
            elif isinstance(item, IRStruct):
                self.structs[item.name] = item
                for field in item.fields:
                    self.symbol_types[field.symbol] = field.type
                    self.struct_fields[(item.name, field.name)] = field.type
            elif isinstance(item, IRImpl):
                for method in item.methods:
                    self.functions[method.symbol] = method
                    self.methods[(item.target_type, method.name)] = method
                    self.method_owner[method.symbol] = item.target_type
                    self.function_returns[method.symbol] = method.return_type
                    for index, parameter in enumerate(method.params):
                        value_type = parameter.type
                        if index == 0 and parameter.name in ("self", "this"):
                            value_type = IRType(item.target_type)
                        self.symbol_types[parameter.symbol] = value_type
            elif isinstance(item, IRTrait):
                for method in item.methods:
                    self.functions[method.symbol] = method
                    self.function_returns[method.symbol] = method.return_type
                    for parameter in method.params:
                        self.symbol_types[parameter.symbol] = parameter.type
            elif isinstance(item, IRVarDecl):
                self.symbol_types[item.symbol] = item.type

    def type_of_symbol(self, symbol: str, fallback: IRType = ANY) -> IRType:
        return self.symbol_types.get(symbol, fallback)

    def return_type(self, function: IRFunction) -> IRType:
        return self.function_returns.get(function.symbol, function.return_type)

    def field_type(self, struct_name: str, field_name: str, fallback: IRType = ANY) -> IRType:
        return self.struct_fields.get((struct_name, field_name), fallback)

    def expression_type(self, node: IRExpr) -> IRType:
        if isinstance(node, IRReference):
            return self.type_of_symbol(node.symbol, node.type)
        if isinstance(node, IRCall):
            if node.callee_symbol.startswith("type::struct::"):
                return IRType(node.callee)
            function = self.functions.get(node.callee_symbol)
            if function is not None:
                result = self.return_type(function)
                return task_of(result) if function.is_async else result
            if node.receiver is not None:
                receiver_type = _strip_optional(self.expression_type(node.receiver))
                method = self.methods.get((receiver_type.name, node.callee))
                if method is not None:
                    result = self.return_type(method)
                    return task_of(result) if method.is_async else result
            return node.type
        if isinstance(node, IRAwait):
            awaited = self.expression_type(node.expr)
            if awaited.name == "Task" and awaited.arguments:
                return awaited.arguments[0]
            return node.type
        if isinstance(node, IRResultPropagate):
            return node.type
        if isinstance(node, IRMemberAccess):
            owner = _strip_optional(self.expression_type(node.obj)).name
            value_type = self.field_type(owner, node.member, node.type)
            return value_type.with_optional() if node.safe else value_type
        if isinstance(node, IRIndexAccess):
            owner = self.expression_type(node.obj)
            if owner.name == "string":
                return STRING
            if owner.name == "Array" and owner.arguments:
                return owner.arguments[0]
            return node.type
        if isinstance(node, IRArray):
            if node.elements:
                result = self.expression_type(node.elements[0])
                for element in node.elements[1:]:
                    result = _merge_types(result, self.expression_type(element))
                return array_of(result)
            return node.type
        if isinstance(node, IRNullCoalesce):
            left = _strip_optional(self.expression_type(node.left))
            return _merge_types(left, self.expression_type(node.right))
        if isinstance(node, IRConditional):
            return _merge_types(
                self.expression_type(node.then_expr),
                self.expression_type(node.else_expr),
            )
        if isinstance(node, IRMatchExpression):
            result = ANY
            for case in node.cases:
                result = _merge_types(result, self.expression_type(case.value))
            return result
        if isinstance(node, IRBinary):
            if _is_known(node.type):
                return node.type
            if node.op in ("==", "!=", "<", ">", "<=", ">=", "and", "or", "&&", "||"):
                return BOOL
            left = self.expression_type(node.left)
            right = self.expression_type(node.right)
            if node.op == "+" and (left.name == "string" or right.name == "string"):
                return STRING
            return _merge_types(left, right)
        if isinstance(node, IRUnary):
            return BOOL if node.op in ("!", "not") else self.expression_type(node.expr)
        if isinstance(node, IRLambda):
            return node.type
        return node.type

    def _update_symbol(self, symbol: str, candidate: IRType) -> None:
        current = self.symbol_types.get(symbol, ANY)
        # This pass fills legacy ``any`` holes; it must never rewrite a
        # concrete Rove declaration merely because a use site performs a legal
        # widening conversion (for example int passed to a float parameter).
        if _is_known(current):
            return
        merged = _merge_types(current, candidate)
        if merged != current:
            self.symbol_types[symbol] = merged
            self.changed = True

    def _update_return(self, symbol: str, candidate: IRType) -> None:
        current = self.function_returns.get(symbol, ANY)
        if _is_known(current):
            return
        merged = _merge_types(current, candidate)
        if merged != current:
            self.function_returns[symbol] = merged
            self.changed = True

    def _update_field(self, owner: str, field: str, candidate: IRType) -> None:
        key = (owner, field)
        current = self.struct_fields.get(key, ANY)
        if _is_known(current):
            return
        merged = _merge_types(current, _strip_optional(candidate))
        if merged != current:
            self.struct_fields[key] = merged
            struct = self.structs.get(owner)
            if struct is not None:
                for parameter in struct.fields:
                    if parameter.name == field:
                        self._update_symbol(parameter.symbol, merged)
                        break
            self.changed = True

    def _constrain_expr(self, node: IRExpr, expected: IRType) -> None:
        if not _is_known(expected):
            return
        if isinstance(node, IRReference):
            self._update_symbol(node.symbol, expected)
        elif isinstance(node, IRMemberAccess):
            owner = _strip_optional(self.expression_type(node.obj)).name
            self._update_field(owner, node.member, _strip_optional(expected))
        elif isinstance(node, IRNullCoalesce):
            self._constrain_expr(node.left, expected.with_optional())
            self._constrain_expr(node.right, expected)
        elif isinstance(node, IRConditional):
            self._constrain_expr(node.then_expr, expected)
            self._constrain_expr(node.else_expr, expected)
        elif isinstance(node, IRMatchExpression):
            for case in node.cases:
                self._constrain_expr(case.value, expected)
        elif isinstance(node, IRCall):
            function = self.functions.get(node.callee_symbol)
            if function is not None:
                if function.is_async:
                    if expected.name == "Task" and expected.arguments:
                        self._update_return(function.symbol, expected.arguments[0])
                else:
                    self._update_return(function.symbol, expected)
        elif isinstance(node, IRAwait):
            self._constrain_expr(node.expr, task_of(expected))
        elif isinstance(node, IRResultPropagate):
            self._scan_expr(node.expr)
        elif isinstance(node, IRBinary):
            if node.op in ("+", "-", "*", "/", "%", "|", "&", "^", "<<", ">>"):
                self._constrain_expr(node.left, expected)
                self._constrain_expr(node.right, expected)

    def _scan_module(self) -> None:
        for item in self.module.items:
            if isinstance(item, IRFunction):
                self._scan_function(item)
            elif isinstance(item, IRImpl):
                for method in item.methods:
                    self._scan_function(method)
            elif isinstance(item, IRTrait):
                for method in item.methods:
                    self._scan_function(method)
            elif isinstance(item, IRStatement):
                self._scan_statement(item, None)

    def _scan_function(self, function: IRFunction) -> None:
        return_exprs: List[IRExpr] = []
        self._collect_returns(function.body, return_exprs)
        if not return_exprs and function.return_type in (ANY, VOID):
            self._update_return(function.symbol, VOID)
        for expression in return_exprs:
            declared = self.function_returns.get(function.symbol, function.return_type)
            if _is_known(declared):
                self._constrain_expr(expression, declared)
            self._scan_expr(expression)
            self._update_return(function.symbol, self.expression_type(expression))
        for statement in function.body:
            self._scan_statement(statement, function)

    def _collect_returns(self, statements: Sequence[IRStatement], output: List[IRExpr]) -> None:
        for statement in statements:
            if isinstance(statement, IRReturn) and statement.expr is not None:
                output.append(statement.expr)
            elif isinstance(statement, IRIf):
                self._collect_returns(statement.then_branch, output)
                for _, body in statement.elif_branches:
                    self._collect_returns(body, output)
                if statement.else_branch is not None:
                    self._collect_returns(statement.else_branch, output)
            elif isinstance(statement, (IRWhile, IRFor, IRGuard, IRUnsafeBlock, IRSpawn, IRTestBlock)):
                body = statement.else_body if isinstance(statement, IRGuard) else statement.body
                self._collect_returns(body, output)
            elif isinstance(statement, IRTryCatch):
                self._collect_returns(statement.try_body, output)
                self._collect_returns(statement.catch_body, output)
            elif isinstance(statement, IRMatch):
                for case in statement.cases:
                    self._collect_returns(case.body, output)

    def _scan_statement(self, node: IRStatement, owner: Optional[IRFunction]) -> None:
        if isinstance(node, IRVarDecl):
            self._scan_expr(node.expr)
            if _is_known(node.type):
                self._update_symbol(node.symbol, node.type)
                self._constrain_expr(node.expr, node.type)
            self._update_symbol(node.symbol, self.expression_type(node.expr))
        elif isinstance(node, IRAssign):
            self._scan_expr(node.target)
            self._scan_expr(node.expr)
            target_type = self.expression_type(node.target)
            value_type = self.expression_type(node.expr)
            self._constrain_expr(node.target, value_type)
            self._constrain_expr(node.expr, target_type)
        elif isinstance(node, IRExprStatement):
            self._scan_expr(node.expr)
        elif isinstance(node, IRReturn):
            if node.expr is not None:
                self._scan_expr(node.expr)
        elif isinstance(node, IRThrow):
            self._scan_expr(node.expr)
        elif isinstance(node, IRIf):
            self._scan_expr(node.condition)
            for statement in node.then_branch:
                self._scan_statement(statement, owner)
            for condition, body in node.elif_branches:
                self._scan_expr(condition)
                for statement in body:
                    self._scan_statement(statement, owner)
            if node.else_branch is not None:
                for statement in node.else_branch:
                    self._scan_statement(statement, owner)
        elif isinstance(node, IRWhile):
            self._scan_expr(node.condition)
            for statement in node.body:
                self._scan_statement(statement, owner)
        elif isinstance(node, IRFor):
            if node.collection_expr is not None:
                self._scan_expr(node.collection_expr)
                collection_type = self.expression_type(node.collection_expr)
                if collection_type.name == "Array" and collection_type.arguments:
                    self._update_symbol(node.symbol, collection_type.arguments[0])
                elif collection_type.name == "string":
                    self._update_symbol(node.symbol, STRING)
            else:
                if node.start_expr is not None:
                    self._scan_expr(node.start_expr)
                if node.end_expr is not None:
                    self._scan_expr(node.end_expr)
                self._update_symbol(node.symbol, INT)
            for statement in node.body:
                self._scan_statement(statement, owner)
        elif isinstance(node, IRDefer):
            self._scan_expr(node.expr)
        elif isinstance(node, IRGuard):
            self._scan_expr(node.condition)
            for statement in node.else_body:
                self._scan_statement(statement, owner)
        elif isinstance(node, (IRUnsafeBlock, IRSpawn, IRTestBlock)):
            for statement in node.body:
                self._scan_statement(statement, owner)
        elif isinstance(node, IRAssert):
            self._scan_expr(node.condition)
        elif isinstance(node, IRMatch):
            self._scan_expr(node.expr)
            for case in node.cases:
                self._scan_expr(case.pattern)
                for statement in case.body:
                    self._scan_statement(statement, owner)
        elif isinstance(node, IRTryCatch):
            self._update_symbol(node.error_symbol, STRING)
            for statement in node.try_body:
                self._scan_statement(statement, owner)
            for statement in node.catch_body:
                self._scan_statement(statement, owner)

    def _scan_expr(self, node: IRExpr) -> None:
        if isinstance(node, IRBinary):
            self._scan_expr(node.left)
            self._scan_expr(node.right)
            if node.op == "+" and self.expression_type(node) == STRING:
                self._constrain_expr(node.left, STRING)
                self._constrain_expr(node.right, STRING)
            elif node.op in ("==", "!=", "<", ">", "<=", ">="):
                left = self.expression_type(node.left)
                right = self.expression_type(node.right)
                self._constrain_expr(node.left, right)
                self._constrain_expr(node.right, left)
        elif isinstance(node, IRUnary):
            self._scan_expr(node.expr)
        elif isinstance(node, IRAwait):
            self._scan_expr(node.expr)
        elif isinstance(node, IRResultPropagate):
            self._scan_expr(node.expr)
        elif isinstance(node, IRCall):
            if node.receiver is not None:
                self._scan_expr(node.receiver)
            for argument in node.args:
                self._scan_expr(argument)
            if node.callee_symbol.startswith("type::struct::"):
                struct = self.structs.get(node.callee)
                if struct is not None:
                    for field, argument in zip(struct.fields, node.args):
                        self._update_field(struct.name, field.name, self.expression_type(argument))
                        expected = self.field_type(struct.name, field.name, field.type)
                        self._constrain_expr(argument, expected)
                return
            function = self.functions.get(node.callee_symbol)
            if function is None and node.receiver is not None:
                receiver_type = _strip_optional(self.expression_type(node.receiver))
                function = self.methods.get((receiver_type.name, node.callee))
            if function is not None:
                parameters = list(function.params)
                if node.receiver is not None and parameters and parameters[0].name in ("self", "this"):
                    self._update_symbol(parameters[0].symbol, _strip_optional(self.expression_type(node.receiver)))
                    parameters = parameters[1:]
                for parameter, argument in zip(parameters, node.args):
                    argument_type = self.expression_type(argument)
                    self._update_symbol(parameter.symbol, argument_type)
                    expected = self.type_of_symbol(parameter.symbol, parameter.type)
                    self._constrain_expr(argument, expected)
        elif isinstance(node, IRMemberAccess):
            self._scan_expr(node.obj)
        elif isinstance(node, IRIndexAccess):
            self._scan_expr(node.obj)
            self._scan_expr(node.index)
        elif isinstance(node, IRArray):
            for element in node.elements:
                self._scan_expr(element)
        elif isinstance(node, IRNullCoalesce):
            self._scan_expr(node.left)
            self._scan_expr(node.right)
            right = self.expression_type(node.right)
            self._constrain_expr(node.left, right.with_optional())
            self._constrain_expr(node.right, _strip_optional(self.expression_type(node.left)))
        elif isinstance(node, IRConditional):
            self._scan_expr(node.condition)
            self._scan_expr(node.then_expr)
            self._scan_expr(node.else_expr)
            result_type = self.expression_type(node)
            self._constrain_expr(node.then_expr, result_type)
            self._constrain_expr(node.else_expr, result_type)
        elif isinstance(node, IRMatchExpression):
            self._scan_expr(node.subject)
            subject_type = self.expression_type(node.subject)
            for case in node.cases:
                if case.pattern is not None:
                    self._scan_expr(case.pattern)
                    self._constrain_expr(case.pattern, subject_type)
                self._scan_expr(case.value)
            result_type = self.expression_type(node)
            for case in node.cases:
                self._constrain_expr(case.value, result_type)
        elif isinstance(node, IRLambda):
            for parameter in node.params:
                self.symbol_types.setdefault(parameter.symbol, parameter.type)
            self._scan_expr(node.body)


class HIRCppEmitter:
    """Emit a standalone hosted C++20 translation unit from verified HIR."""

    _KNOWN_CRT_FUNCTIONS = frozenset(
        "getenv system exit _exit abort malloc calloc realloc free abs labs llabs puts "
        "putchar getchar printf scanf sprintf snprintf strlen wcslen sqrt pow sin cos tan "
        "memset memcpy memmove strcpy strncpy strcmp strncmp strcat strncat fopen fclose "
        "fread fwrite fseek ftell rewind clock time".split()
    )

    _BUILTIN_NAMES = {
        "print": "_nyx_print",
        "input": "_nyx_input",
        "to_string": "_nyx_to_string",
        "to_str": "_nyx_to_string",
        "to_int": "_nyx_to_int",
        "contains": "_nyx_contains",
        "is_number": "_nyx_is_number",
        "addr": "_nyx_addr",
        "peek": "_nyx_peek",
        "memdump": "_nyx_memdump",
        "delay_ms": "_nyx_delay_ms",
        "channel": "_nyx_channel",
        "Ok": "_nyx_ok",
        "Err": "_nyx_err",
        "len": "_nyx_len",
        "args": "_nyx_args",
        "map": "_nyx_map",
        "filter": "_nyx_filter",
        "fold": "_nyx_fold",
    }

    def __init__(self, module: IRModule):
        self.module = module
        self.inference = ModuleTypeInference(module)
        self._struct_destructors: List[str] = []
        self._struct_constructors: List[str] = []
        self.symbol_names: Dict[str, str] = {}
        self.public_symbols = {
            item.symbol
            for item in module.items
            if isinstance(item, (IRFunction, IRStruct, IRTrait, IRTypeAlias, IREnum, IRExternFunction, IRVarDecl))
        }
        self.impls: Dict[str, List[IRImpl]] = defaultdict(list)
        self.externs: Dict[str, IRExternFunction] = {}
        self.declared_types = {
            item.name
            for item in module.items
            if isinstance(item, (IRStruct, IRTrait, IRTypeAlias, IREnum))
        }
        self.payload_enums = {
            item.name: item
            for item in module.items
            if isinstance(item, IREnum) and any(member.is_variant for member in item.members)
        }
        self.enum_variants = {
            f"enum::{item.name}::variant::{member.name}": (item, member)
            for item in self.payload_enums.values()
            for member in item.members if member.is_variant
        }
        self.current_return_type: Optional[IRType] = None
        self.counter = 0
        for item in module.items:
            if isinstance(item, IRImpl):
                self.impls[item.target_type].append(item)
            elif isinstance(item, IRExternFunction):
                self.externs[item.symbol] = item
        self._register_declarations()

    def emit(self) -> str:
        lines: List[str] = []
        lines.extend(self._emit_native_directives())
        lines.extend(self._emit_foreign_imports())

        aliases = [item for item in self.module.items if isinstance(item, IRTypeAlias)]
        enums = [item for item in self.module.items if isinstance(item, IREnum)]
        traits = [item for item in self.module.items if isinstance(item, IRTrait)]
        structs = [item for item in self.module.items if isinstance(item, IRStruct)]
        externs = [item for item in self.module.items if isinstance(item, IRExternFunction)]
        functions = [item for item in self.module.items if isinstance(item, IRFunction)]
        statements = [item for item in self.module.items if isinstance(item, IRStatement)]

        for struct in structs:
            if struct.generic_params:
                params = ", ".join(f"typename {self._identifier(name)}" for name in struct.generic_params)
                lines.append(f"template <{params}> struct {self._symbol(struct.symbol, struct.name)};")
            else:
                lines.append(f"struct {self._symbol(struct.symbol, struct.name)};")
        if structs:
            lines.append("")

        for alias in aliases:
            lines.extend(self._emit_type_alias(alias))
        for enum in enums:
            lines.extend(self._emit_enum(enum))
        for trait in traits:
            lines.extend(self._emit_trait(trait))
        if aliases or enums or traits:
            lines.append("")

        for external in externs:
            declaration = self._emit_extern(external)
            if declaration:
                lines.extend(declaration)
        if externs:
            lines.append("")

        for function in functions:
            lines.extend(self._emit_function_forward(function))
        if functions:
            lines.append("")

        # Inline impl methods may call module functions. Struct forward
        # declarations make function signatures legal before full struct
        # definitions, so emit callable prototypes first.
        for struct in self._order_structs(structs):
            lines.extend(self._emit_struct(struct))
        if self._struct_constructors:
            lines.extend(self._struct_constructors)
        if self._struct_destructors:
            lines.extend(self._struct_destructors)
        if structs:
            lines.append("")

        globals_ = [statement for statement in statements if isinstance(statement, IRVarDecl)]
        executable = [statement for statement in statements if not isinstance(statement, IRVarDecl)]
        for declaration in globals_:
            lines.extend(self._emit_var(declaration, 0, global_scope=True))
        if globals_:
            lines.append("")

        for function in functions:
            lines.extend(self._emit_function(function, 0))
            lines.append("")

        lines.append("int main(int argc, char** argv) {")
        lines.append("    for (int index = 0; index < argc; ++index) {")
        lines.append("        _nyx_cli_arguments.emplace_back(argv[index] ? argv[index] : \"\");")
        lines.append("    }")
        lines.append("#ifdef _WIN32")
        lines.append("    SetConsoleOutputCP(65001);")
        lines.append("    SetConsoleCP(65001);")
        lines.append("#endif")
        for statement in executable:
            lines.extend(self._emit_statement(statement, 1))

        user_main = next((function for function in functions if function.name == "main"), None)
        explicitly_called = any(
            isinstance(statement, IRExprStatement)
            and isinstance(statement.expr, IRCall)
            and statement.expr.receiver is None
            and statement.expr.callee == "main"
            for statement in executable
        )
        if user_main is not None and not explicitly_called:
            suffix = ".get()" if user_main.is_async else ""
            lines.append(f"    {self._symbol(user_main.symbol, user_main.name)}(){suffix};")
        lines.append("    _nyx_pause_if_standalone_console();")
        lines.append("    return 0;")
        lines.append("}")
        body = "\n".join(lines).rstrip() + "\n"
        runtime = self._runtime_for_body(body)
        return runtime.rstrip() + "\n\n" + body

    def _runtime_for_body(self, body: str) -> str:
        """Select the smallest runtime whose contract covers the emitted unit.

        This deliberately starts with a narrow scalar/print fast path. Any
        advanced Rove type, native interop, async surface, aggregate storage, or
        unrecognized runtime reference keeps the established full runtime.
        """
        complex_items = (
            IRStruct,
            IRTrait,
            IRTypeAlias,
            IREnum,
            IRExternFunction,
            IRForeignImport,
            IRNativeDirective,
        )
        if any(isinstance(item, complex_items) for item in self.module.items):
            return _CPP_RUNTIME
        if any(
            isinstance(item, IRFunction) and item.is_async
            for item in self.module.items
        ):
            return _CPP_RUNTIME

        references = set(re.findall(r"\b(?:_nyx|nyx)_[A-Za-z0-9_]+", body))
        allowed = {
            "_nyx_cli_arguments",
            "_nyx_pause_if_standalone_console",
            "_nyx_print",
            "_nyx_user_main",
        }
        if references - allowed:
            return _CPP_RUNTIME
        if any(
            token in body
            for token in (
                "NyxResult",
                "NyxEnumValue",
                "NyxIterator",
                "_Nyx",
                "std::any",
                "std::function<",
                "std::optional<",
                "std::shared_future<",
                "std::variant<",
                "std::vector<",
                "co_await",
                "co_return",
                "co_yield",
            )
        ):
            return _CPP_RUNTIME
        return _CPP_COMPACT_RUNTIME

    def _register_declarations(self) -> None:
        for item in self.module.items:
            if isinstance(item, IRFunction):
                preferred = "_nyx_user_main" if item.name == "main" else item.name
                emitted = self._identifier(preferred)
                if item.name in ("abs", "min", "max"):
                    emitted = f"_nyx_user_{item.name}"
                self.symbol_names[item.symbol] = emitted
            elif isinstance(item, (IRStruct, IRTrait, IRTypeAlias, IREnum, IRExternFunction, IRVarDecl, IRForeignImport)):
                preferred = item.alias if isinstance(item, IRForeignImport) else item.name
                self.symbol_names[item.symbol] = self._identifier(preferred)
            if isinstance(item, IREnum):
                for member in item.members:
                    if member.is_variant:
                        self.symbol_names[f"enum::{item.name}::variant::{member.name}"] = self._identifier(member.name)
        for name, emitted in self._BUILTIN_NAMES.items():
            self.symbol_names[f"builtin::{name}"] = emitted

    def _emit_native_directives(self) -> List[str]:
        directives = [item for item in self.module.items if isinstance(item, IRNativeDirective)]
        lines: List[str] = []
        seen_includes = set()
        for directive in directives:
            if directive.kind != "include" or directive.value in seen_includes:
                continue
            seen_includes.add(directive.value)
            value = directive.value.strip()
            if value.startswith(("<", '"')):
                lines.append(f"#include {value}")
            else:
                lines.append(f"#include <{value}>")
        if seen_includes:
            lines.append("")

        for directive in directives:
            if directive.kind == "use":
                value = directive.value.strip().rstrip(";")
                if value.startswith("using "):
                    lines.append(value + ";")
                elif value.startswith("namespace "):
                    lines.append("using " + value + ";")
                elif "::" in value:
                    lines.append(f"using {value};")
                else:
                    lines.append(f"using namespace {value};")
            elif directive.kind == "raw":
                lines.append("// --- BEGIN ROVE NATIVE RAW ---")
                lines.extend(directive.value.splitlines())
                lines.append("// --- END ROVE NATIVE RAW ---")
        if lines:
            lines.append("")
        return lines

    def _emit_foreign_imports(self) -> List[str]:
        lines: List[str] = []
        for item in self.module.items:
            if not isinstance(item, IRForeignImport):
                continue
            if item.ecosystem != "cpp":
                raise CppEmissionError(
                    f"C++ target cannot consume '{item.ecosystem}' foreign import '{item.module}'"
                )
            source = item.source.strip()
            if not source:
                raise CppEmissionError("C++ foreign import requires a header source")
            if not source.startswith(("<", '"')):
                source = f"<{source}>"
            if not re.fullmatch(r'(?:<[A-Za-z0-9_./+\-]+>|"[A-Za-z0-9_./+\-]+")', source):
                raise CppEmissionError(f"Invalid C++ header source '{item.source}'")
            if not re.fullmatch(r"[A-Za-z_]\w*(?:::[A-Za-z_]\w*)*", item.module):
                raise CppEmissionError(f"Invalid C++ namespace path '{item.module}'")
            lines.append(f"#include {source}")
            lines.append(f"namespace {self._symbol(item.symbol, item.alias)} = {item.module};")
        if lines:
            lines.append("")
        return lines

    def _order_structs(self, structs: Sequence[IRStruct]) -> List[IRStruct]:
        # Rove declaration order is semantically significant for inline impl
        # methods: a later struct may take an earlier one by value even when no
        # field dependency exists.  Front declarations cover recursive vectors;
        # retaining source order covers method signatures and bodies.
        return list(structs)

    def _emit_type_alias(self, node: IRTypeAlias) -> List[str]:
        return [
            f"using {self._symbol(node.symbol, node.name)} = {self._cpp_type(node.actual_type, role='alias')};"
        ]

    def _emit_enum(self, node: IREnum) -> List[str]:
        if any(member.is_variant for member in node.members):
            lines = [f"using {self._symbol(node.symbol, node.name)} = NyxEnumValue;"]
            for member in node.members:
                if not member.is_variant:
                    raise CppEmissionError(
                        f"Payload enum '{node.name}' cannot mix discriminant member '{member.name}'"
                    )
                parameters = []
                values = []
                template_params = []
                for index, payload_type in enumerate(member.payload_types):
                    parameter_name = f"_nyx_payload_{index}"
                    if payload_type.name in node.generic_params:
                        template_name = f"_NyxPayload{index}"
                        template_params.append(f"typename {template_name}")
                        parameters.append(f"{template_name}&& {parameter_name}")
                        values.append(f"std::any(std::forward<{template_name}>({parameter_name}))")
                    else:
                        parameters.append(
                            f"{self._cpp_type(payload_type, role='parameter')} {parameter_name}"
                        )
                        values.append(f"std::any({parameter_name})")
                if template_params:
                    lines.append(f"template <{', '.join(template_params)}>")
                constructor = self._symbol(
                    f"enum::{node.name}::variant::{member.name}", member.name
                )
                lines.append(
                    f"inline NyxEnumValue {constructor}({', '.join(parameters)}) {{ "
                    f"return {{{self._string_literal(node.name)}, {self._string_literal(member.name)}, "
                    f"std::vector<std::any>{{{', '.join(values)}}}}}; }}"
                )
            return lines
        members = []
        for member in node.members:
            if member.value is None:
                members.append(self._identifier(member.name))
            else:
                members.append(f"{self._identifier(member.name)} = {self._expr(member.value)}")
        return [
            f"enum class {self._symbol(node.symbol, node.name)} {{ {', '.join(members)} }};"
        ]

    def _emit_trait(self, node: IRTrait) -> List[str]:
        name = self._symbol(node.symbol, node.name)
        lines = [f"class {name} {{", "public:", f"    virtual ~{name}() = default;"]
        for method in node.methods:
            return_type = self.inference.return_type(method)
            if not _is_known(return_type):
                raise CppEmissionError(
                    f"Cannot infer trait method return type '{node.name}.{method.name}'"
                )
            parameters = []
            for parameter in method.params:
                if parameter.name in ("self", "this"):
                    continue
                value_type = self.inference.type_of_symbol(parameter.symbol, parameter.type)
                parameters.append(
                    f"{self._cpp_type(value_type, role='parameter')} {self._parameter_name(parameter.symbol, parameter.name)}"
                )
            rendered_return = self._cpp_type(return_type, role="return")
            if method.is_async:
                rendered_return = f"NyxTask<{rendered_return}>"
            lines.append(
                f"    virtual {rendered_return} "
                f"{self._identifier(method.name)}({', '.join(parameters)}) = 0;"
            )
        lines.append("};")
        return lines

    def _emit_struct(self, node: IRStruct) -> List[str]:
        name = self._symbol(node.symbol, node.name)
        lines: List[str] = []
        if node.generic_params:
            params = ", ".join(f"typename {self._identifier(item)}" for item in node.generic_params)
            lines.append(f"template <{params}>")
        base_traits = [
            self._identifier(impl.trait_name)
            for impl in self.impls.get(node.name, ())
            if impl.trait_name
        ]
        inheritance = "" if not base_traits else " : " + ", ".join(
            f"public {trait}" for trait in base_traits
        )
        lines.append(f"struct {name}{inheritance} {{")

        field_types: Dict[str, IRType] = {}
        for field in node.fields:
            value_type = self.inference.field_type(node.name, field.name, field.type)
            if not _is_known(value_type):
                raise CppEmissionError(
                    f"Cannot infer native type for field '{node.name}.{field.name}'; add a Rove annotation"
                )
            field_types[field.name] = value_type
            initializer = "{}" if node.generic_params else ""
            lines.append(
                f"    {self._cpp_type(value_type, role='field')} "
                f"{self._identifier(field.name)}{initializer};"
            )

        if node.generic_params:
            lines.append(f"    {name}() = default;")
        else:
            lines.append(f"    {name}();")
            default_initializers = ", ".join(
                f"{self._identifier(field.name)}()" for field in node.fields
            )
            initializer_list = f" : {default_initializers}" if default_initializers else ""
            self._struct_constructors.append(f"{name}::{name}(){initializer_list} {{}}")
        if node.fields:
            parameters = []
            definition_parameters = []
            initializers = []
            for field in node.fields:
                field_name = self._identifier(field.name)
                parameter_name = f"_nyx_{field_name}"
                value_type = field_types[field.name]
                rendered_type = self._cpp_type(value_type, role='parameter')
                parameter = f"{rendered_type} {parameter_name}"
                if field.default is not None:
                    parameter += f" = {self._expr(field.default, value_type)}"
                parameters.append(parameter)
                definition_parameters.append(f"{rendered_type} {parameter_name}")
                initializers.append(f"{field_name}(std::move({parameter_name}))")
            lines.append(f"    {name}({', '.join(parameters)});")
            self._struct_constructors.append(
                f"{name}::{name}({', '.join(definition_parameters)}) : {', '.join(initializers)} {{}}"
            )

        methods = [method for impl in self.impls.get(node.name, ()) for method in impl.methods]
        for method in methods:
            lines.extend(self._emit_method(method, node.name, 1))
        drop_method = next(
            (method for method in methods if method.name in ("drop", "destroy", "cleanup", "dispose")),
            None,
        )
        if drop_method is not None:
            lines.append(f"    ~{name}() {{ this->{self._identifier(drop_method.name)}(); }}")
        elif not node.generic_params:
            lines.append(f"    ~{name}();")
            self._struct_destructors.append(f"{name}::~{name}() = default;")
        lines.append("};")
        return lines

    def _emit_method(self, node: IRFunction, owner: str, indent: int) -> List[str]:
        prefix = "    " * indent
        parameters = []
        has_receiver = bool(node.params and node.params[0].name in ("self", "this"))
        for index, parameter in enumerate(node.params):
            if index == 0 and parameter.name in ("self", "this"):
                self.symbol_names[parameter.symbol] = "this"
                continue
            value_type = self.inference.type_of_symbol(parameter.symbol, parameter.type)
            rendered_type = self._cpp_type(value_type, role="parameter")
            name = self._parameter_name(parameter.symbol, parameter.name)
            rendered = f"{rendered_type} {name}"
            if parameter.default is not None:
                rendered += f" = {self._expr(parameter.default, value_type)}"
            parameters.append(rendered)
        return_type = self.inference.return_type(node)
        if not _is_known(return_type):
            raise CppEmissionError(f"Cannot infer return type for method '{owner}.{node.name}'")
        rendered_return = self._cpp_type(return_type, role="return")
        public_return = f"NyxTask<{rendered_return}>" if node.is_async else rendered_return
        lines = [f"{prefix}{public_return} {self._identifier(node.name)}({', '.join(parameters)}) {{"]
        previous = self.current_return_type
        self.current_return_type = return_type
        try:
            if node.is_async:
                capture = "[=, this]" if has_receiver else "[=]"
                lines.append(
                    f"{prefix}    return _nyx_async({capture}() mutable -> {rendered_return} {{"
                )
                lines.extend(self._emit_block(node.body, indent + 2))
                lines.append(f"{prefix}    }});")
            else:
                lines.extend(self._emit_block(node.body, indent + 1))
        finally:
            self.current_return_type = previous
        lines.append(f"{prefix}}}")
        return lines

    def _emit_extern(self, node: IRExternFunction) -> List[str]:
        if node.name in self._KNOWN_CRT_FUNCTIONS or node.name.startswith(("nyx_hal_", "nyx_mmio_")):
            return []
        parameters = []
        for parameter in node.params:
            value_type = self.inference.type_of_symbol(parameter.symbol, parameter.type)
            parameters.append(
                self._c_ffi_parameter_declaration(
                    value_type,
                    self._parameter_name(parameter.symbol, parameter.name),
                )
            )
        if node.varargs:
            parameters.append("...")
        abi = 'extern "C" ' if node.abi.upper() == "C" else ""
        return [
            f"{abi}{self._c_ffi_type(node.return_type)} "
            f"{self._symbol(node.symbol, node.name)}({', '.join(parameters)});"
        ]

    def _emit_function_forward(self, node: IRFunction) -> List[str]:
        return_type = self.inference.return_type(node)
        if not _is_known(return_type):
            raise CppEmissionError(f"Cannot infer return type for function '{node.name}'")
        lines = []
        if node.generic_params:
            params = ", ".join(f"typename {self._identifier(item)}" for item in node.generic_params)
            lines.append(f"template <{params}>")
        parameters = []
        for parameter in node.params:
            value_type = self.inference.type_of_symbol(parameter.symbol, parameter.type)
            rendered = (
                f"{self._cpp_type(value_type, role='parameter')} "
                f"{self._parameter_name(parameter.symbol, parameter.name)}"
            )
            if parameter.default is not None:
                rendered += f" = {self._expr(parameter.default, value_type)}"
            parameters.append(rendered)
        rendered_return = self._cpp_type(return_type, role="return")
        if node.is_async:
            rendered_return = f"NyxTask<{rendered_return}>"
        lines.append(
            f"{rendered_return} "
            f"{self._symbol(node.symbol, node.name)}({', '.join(parameters)});"
        )
        return lines

    def _emit_function(self, node: IRFunction, indent: int) -> List[str]:
        prefix = "    " * indent
        return_type = self.inference.return_type(node)
        if not _is_known(return_type):
            raise CppEmissionError(f"Cannot infer return type for function '{node.name}'")
        lines: List[str] = []
        if node.generic_params:
            params = ", ".join(f"typename {self._identifier(item)}" for item in node.generic_params)
            lines.append(f"{prefix}template <{params}>")
        parameters = []
        for parameter in node.params:
            value_type = self.inference.type_of_symbol(parameter.symbol, parameter.type)
            parameters.append(
                f"{self._cpp_type(value_type, role='parameter')} "
                f"{self._parameter_name(parameter.symbol, parameter.name)}"
            )
        rendered_return = self._cpp_type(return_type, role="return")
        public_return = f"NyxTask<{rendered_return}>" if node.is_async else rendered_return
        lines.append(
            f"{prefix}{public_return} "
            f"{self._symbol(node.symbol, node.name)}({', '.join(parameters)}) {{"
        )
        previous = self.current_return_type
        self.current_return_type = return_type
        try:
            if node.is_async:
                lines.append(
                    f"{prefix}    return _nyx_async([=]() mutable -> {rendered_return} {{"
                )
                if return_type.name == "Result" and len(return_type.arguments) == 2:
                    success_type = self._cpp_type(return_type.arguments[0], role="result")
                    error_type = self._cpp_type(return_type.arguments[1], role="result")
                    lines.append(f"{prefix}        try {{")
                    lines.extend(self._emit_block(node.body, indent + 3))
                    lines.append(f"{prefix}        }} catch (const _NyxResultPropagation& propagated) {{")
                    lines.append(
                        f"{prefix}            return {{false, {success_type}{{}}, "
                        f"std::any_cast<{error_type}>(propagated.error)}};"
                    )
                    lines.append(f"{prefix}        }}")
                else:
                    lines.extend(self._emit_block(node.body, indent + 2))
                lines.append(f"{prefix}    }});")
            else:
                if return_type.name == "Result" and len(return_type.arguments) == 2:
                    success_type = self._cpp_type(return_type.arguments[0], role="result")
                    error_type = self._cpp_type(return_type.arguments[1], role="result")
                    lines.append(f"{prefix}    try {{")
                    lines.extend(self._emit_block(node.body, indent + 2))
                    lines.append(f"{prefix}    }} catch (const _NyxResultPropagation& propagated) {{")
                    lines.append(
                        f"{prefix}        return {{false, {success_type}{{}}, "
                        f"std::any_cast<{error_type}>(propagated.error)}};"
                    )
                    lines.append(f"{prefix}    }}")
                else:
                    lines.extend(self._emit_block(node.body, indent + 1))
        finally:
            self.current_return_type = previous
        lines.append(f"{prefix}}}")
        return lines

    def _emit_block(self, statements: Sequence[IRStatement], indent: int) -> List[str]:
        if not statements:
            return ["    " * indent + "// empty"]
        lines: List[str] = []
        for statement in statements:
            lines.extend(self._emit_statement(statement, indent))
        return lines

    def _condition(self, node: IRExpr) -> str:
        rendered = self._expr(node)
        return f"_nyx_require_bool({rendered})" if node.type.is_unknown else rendered

    def _emit_statement(self, node: IRStatement, indent: int) -> List[str]:
        prefix = "    " * indent
        if isinstance(node, IRVarDecl):
            return self._emit_var(node, indent)
        if isinstance(node, IRAssign):
            expected = self.inference.expression_type(node.target)
            return [f"{prefix}{self._expr(node.target)} = {self._expr(node.expr, expected)};"]
        if isinstance(node, IRExprStatement):
            return [f"{prefix}{self._expr(node.expr)};"]
        if isinstance(node, IRReturn):
            if self.current_return_type is not None and self.current_return_type.name == "Iterator":
                if node.expr is not None:
                    raise CppEmissionError("Iterator functions cannot return a value")
                return [f"{prefix}co_return;"]
            if node.expr is None:
                return [f"{prefix}return;"]
            return [f"{prefix}return {self._expr(node.expr, self.current_return_type)};"]
        if isinstance(node, IRThrow):
            return [f"{prefix}throw std::runtime_error(_nyx_to_string({self._expr(node.expr)}));"]
        if isinstance(node, IRYield):
            return [f"{prefix}co_yield {self._expr(node.expr)};"]
        if isinstance(node, IRIf):
            lines = [f"{prefix}if ({self._condition(node.condition)}) {{"]
            lines.extend(self._emit_block(node.then_branch, indent + 1))
            for condition, body in node.elif_branches:
                lines.append(f"{prefix}}} else if ({self._condition(condition)}) {{")
                lines.extend(self._emit_block(body, indent + 1))
            if node.else_branch is not None:
                lines.append(f"{prefix}}} else {{")
                lines.extend(self._emit_block(node.else_branch, indent + 1))
            lines.append(f"{prefix}}}")
            return lines
        if isinstance(node, IRWhile):
            lines = [f"{prefix}while ({self._condition(node.condition)}) {{"]
            lines.extend(self._emit_block(node.body, indent + 1))
            lines.append(f"{prefix}}}")
            return lines
        if isinstance(node, IRFor):
            variable = self._symbol(node.symbol, node.var_name)
            if node.collection_expr is not None:
                collection_type = self.inference.expression_type(node.collection_expr)
                if collection_type.name == "string":
                    source = self._temporary("string_source")
                    offset = self._temporary("string_offset")
                    start = self._temporary("string_start")
                    lines = [
                        f"{prefix}const auto& {source} = {self._expr(node.collection_expr)};",
                        f"{prefix}for (size_t {offset} = 0; {offset} < {source}.size();) {{",
                        f"{prefix}    const size_t {start} = {offset}++;",
                        f"{prefix}    while ({offset} < {source}.size() && "
                        f"(static_cast<unsigned char>({source}[{offset}]) & 0xC0) == 0x80) ++{offset};",
                        f"{prefix}    std::string {variable} = {source}.substr({start}, {offset} - {start});",
                    ]
                else:
                    lines = [
                        f"{prefix}for (auto& {variable} : {self._expr(node.collection_expr)}) {{"
                    ]
            elif node.start_expr is not None and node.end_expr is not None:
                lines = [
                    f"{prefix}for (int64_t {variable} = {self._expr(node.start_expr)}; "
                    f"{variable} <= static_cast<int64_t>({self._expr(node.end_expr)}); ++{variable}) {{"
                ]
            else:
                raise CppEmissionError("HIR for-loop has neither a collection nor a range")
            lines.extend(self._emit_block(node.body, indent + 1))
            lines.append(f"{prefix}}}")
            return lines
        if isinstance(node, IRBreak):
            return [f"{prefix}break;"]
        if isinstance(node, IRContinue):
            return [f"{prefix}continue;"]
        if isinstance(node, IRDefer):
            guard = self._temporary("defer")
            return [
                f"{prefix}auto {guard} = _nyx_make_scope_exit([&]() {{ {self._expr(node.expr)}; }});"
            ]
        if isinstance(node, IRGuard):
            lines = [f"{prefix}if (!({self._condition(node.condition)})) {{"]
            lines.extend(self._emit_block(node.else_body, indent + 1))
            lines.append(f"{prefix}}}")
            return lines
        if isinstance(node, IRUnsafeBlock):
            lines = [f"{prefix}// unsafe boundary"]
            lines.extend(self._emit_block(node.body, indent))
            return lines
        if isinstance(node, IRSpawn):
            lines = [f"{prefix}std::thread([=]() mutable {{"]
            lines.extend(self._emit_block(node.body, indent + 1))
            lines.append(f"{prefix}}}).detach();")
            return lines
        if isinstance(node, IRAssert):
            message = node.message or "Assertion failed"
            return [
                f"{prefix}if (!({self._condition(node.condition)})) "
                f"throw std::runtime_error({self._string_literal(message)});"
            ]
        if isinstance(node, IRMatch):
            return self._emit_match(node, indent)
        if isinstance(node, IRTryCatch):
            error_name = self._symbol(node.error_symbol, node.error_name)
            caught_name = self._temporary("caught")
            lines = [f"{prefix}try {{"]
            lines.extend(self._emit_block(node.try_body, indent + 1))
            lines.append(f"{prefix}}} catch (const std::exception& {caught_name}) {{")
            lines.append(f"{prefix}    const std::string {error_name} = {caught_name}.what();")
            lines.extend(self._emit_block(node.catch_body, indent + 1))
            lines.append(f"{prefix}}}")
            return lines
        if isinstance(node, IRTestBlock):
            lines = [f"{prefix}// test: {node.description}"]
            lines.extend(self._emit_block(node.body, indent))
            return lines
        raise CppEmissionError(f"Unsupported HIR statement: {type(node).__name__}")

    def _emit_var(self, node: IRVarDecl, indent: int, *, global_scope: bool = False) -> List[str]:
        prefix = "    " * indent
        value_type = self.inference.type_of_symbol(node.symbol, node.type)
        rendered_type = self._cpp_type(value_type, role="variable")
        # Rove ``let``/``const`` freeze the binding, not the value reachable
        # through it.  C++ ``const`` would impose a stronger, deep receiver
        # restriction (for example rejecting a method call on ``let worker``)
        # that the JS and Python backends do not have.  The verified HIR is the
        # enforcement boundary for rebinding, so keep the emitted C++ storage
        # mutable and use only the linkage qualifier required at module scope.
        qualifier = "inline " if global_scope else ""
        return [
            f"{prefix}{qualifier}{rendered_type} {self._symbol(node.symbol, node.name)} = "
            f"{self._expr(node.expr, value_type)};"
        ]

    def _emit_match(self, node: IRMatch, indent: int) -> List[str]:
        prefix = "    " * indent
        value = self._temporary("match")
        lines = [f"{prefix}auto {value} = {self._expr(node.expr)};"]
        emitted = False
        for case in node.cases:
            pattern = case.pattern
            wildcard = (
                isinstance(pattern, IRReference) and pattern.name == "_"
            ) or (
                isinstance(pattern, IRLiteral) and pattern.value == "_"
            )
            binding = isinstance(pattern, IRReference) and pattern.name != "_"
            payload_name: Optional[str] = None
            payload_member = "value"
            variant = self.enum_variants.get(pattern.callee_symbol) if isinstance(pattern, IRCall) else None
            if variant is not None:
                enum_node, member = variant
                condition = (
                    f"{value}.enum_name == {self._string_literal(enum_node.name)} && "
                    f"{value}.variant_name == {self._string_literal(member.name)}"
                )
                payload_bindings = []
                for index, argument in enumerate(pattern.args):
                    if not isinstance(argument, IRReference) or argument.name == "_":
                        continue
                    payload_type = argument.type
                    binding_name = self._symbol(argument.symbol, argument.name)
                    if payload_type.is_unknown:
                        payload_bindings.append(
                            f"{prefix}    const std::any& {binding_name} = {value}.payload.at({index});"
                        )
                    else:
                        rendered_type = self._cpp_type(payload_type, role="variable")
                        payload_bindings.append(
                            f"{prefix}    auto {binding_name} = std::any_cast<{rendered_type}>({value}.payload.at({index}));"
                        )
            elif isinstance(pattern, IRCall) and pattern.callee in ("Ok", "Err"):
                expected = "true" if pattern.callee == "Ok" else "false"
                condition = f"{value}.is_ok == {expected}"
                payload_member = "value" if pattern.callee == "Ok" else "error"
                if pattern.args and isinstance(pattern.args[0], IRReference):
                    payload_name = self._symbol(pattern.args[0].symbol, pattern.args[0].name)
            elif wildcard or binding:
                condition = "true"
            elif isinstance(pattern, IRCall):
                raise CppEmissionError(
                    f"Unsupported constructor pattern '{pattern.callee}' on cpp"
                )
            else:
                condition = f"{value} == {self._expr(pattern)}"

            if emitted and (wildcard or binding):
                lines.append(f"{prefix}else {{")
            else:
                keyword = "if" if not emitted else "else if"
                lines.append(f"{prefix}{keyword} ({condition}) {{")
            if binding:
                lines.append(
                    f"{prefix}    const auto& {self._symbol(pattern.symbol, pattern.name)} = {value};"
                )
            if payload_name is not None:
                lines.append(f"{prefix}    auto {payload_name} = {value}.{payload_member};")
            if variant is not None:
                lines.extend(payload_bindings)
            lines.extend(self._emit_block(case.body, indent + 1))
            lines.append(f"{prefix}}}")
            emitted = True
            if wildcard or binding:
                break
        return lines

    def _expr(self, node: IRExpr | None, expected: Optional[IRType] = None) -> str:
        if node is None:
            raise CppEmissionError("Missing HIR expression")
        if isinstance(node, IRLiteral):
            if node.value is None:
                if expected is not None and expected.name == "null":
                    return "nullptr"
                if expected is not None and expected.optional:
                    return "std::nullopt"
                return "nullptr"
            if isinstance(node.value, bool):
                return "true" if node.value else "false"
            if isinstance(node.value, str):
                return self._string_literal(node.value)
            if node.type.name == "int" and node.value == -(1 << 63):
                # Writing -9223372036854775808 directly is ill-formed on C++
                # implementations where its positive token fits no signed type.
                return "(-INT64_C(9223372036854775807) - INT64_C(1))"
            if node.type.name == "int":
                # C++ otherwise gives small literals the host type ``int``.
                # Rove integers are always signed i64, including during template
                # deduction (for example Ok(42) -> Result<int64_t, E>).
                return f"static_cast<int64_t>({node.value})"
            return repr(node.value)
        if isinstance(node, IRReference):
            return self._symbol(node.symbol, node.name)
        if isinstance(node, IRBinary):
            left_type = self.inference.expression_type(node.left)
            right_type = self.inference.expression_type(node.right)
            if isinstance(node.left, IRLiteral) and node.left.value is None:
                left = "std::nullopt" if right_type.optional and right_type.name != "null" else "nullptr"
            else:
                left = self._expr(node.left, right_type)
            if isinstance(node.right, IRLiteral) and node.right.value is None:
                right = "std::nullopt" if left_type.optional and left_type.name != "null" else "nullptr"
            else:
                right = self._expr(node.right, left_type)
            integer_operators = {
                "+": "_nyx_i64_add",
                "-": "_nyx_i64_sub",
                "*": "_nyx_i64_mul",
                "/": "_nyx_i64_div",
                "%": "_nyx_i64_mod",
                "&": "_nyx_i64_and",
                "^": "_nyx_i64_xor",
                "|": "_nyx_i64_or",
                "<<": "_nyx_i64_shl",
                ">>": "_nyx_i64_shr",
            }
            if node.type.name == "int" and node.op in integer_operators:
                return f"{integer_operators[node.op]}({left}, {right})"
            if node.type.name == "float" and node.op == "/":
                return f"_nyx_f64_div({left}, {right})"
            if node.type.name == "float" and node.op == "%":
                return f"_nyx_f64_mod({left}, {right})"
            operator = {"and": "&&", "or": "||"}.get(node.op, node.op)
            return f"({left} {operator} {right})"
        if isinstance(node, IRUnary):
            operator = "!" if node.op in ("!", "not") else node.op
            if node.type.name == "int":
                if node.op == "-":
                    return f"_nyx_i64_neg({self._expr(node.expr)})"
                if node.op == "~":
                    return f"_nyx_i64_not({self._expr(node.expr)})"
                if node.op == "+":
                    return self._expr(node.expr)
            return f"({operator}{self._expr(node.expr)})"
        if isinstance(node, IRAwait):
            return f"({self._expr(node.expr)}).get()"
        if isinstance(node, IRResultPropagate):
            return f"_nyx_propagate({self._expr(node.expr)})"
        if isinstance(node, IRCall):
            if (
                node.callee_symbol.startswith("builtin::")
                and node.callee in ("Ok", "Err")
                and expected is not None
                and expected.name == "Result"
                and len(expected.arguments) >= 2
                and all(_is_known(item) for item in expected.arguments[:2])
                and len(node.args) == 1
            ):
                result_type = self._cpp_type(expected, role="result")
                payload_index = 0 if node.callee == "Ok" else 1
                payload = self._expr(node.args[0], expected.arguments[payload_index])
                if node.callee == "Ok":
                    return f"{result_type}{{true, {payload}, {{}}}}"
                return f"{result_type}{{false, {{}}, {payload}}}"
            if node.receiver is not None:
                receiver = self._expr(node.receiver)
                if (
                    isinstance(node.receiver, IRReference)
                    and node.receiver.symbol.startswith("foreign::cpp::")
                ):
                    separator = "::"
                elif isinstance(node.receiver, IRReference) and node.receiver.name in ("self", "this"):
                    receiver = "this"
                    separator = "->"
                else:
                    separator = "."
                args = ", ".join(self._expr(argument) for argument in node.args)
                if node.callee == "push" and len(node.args) == 1:
                    return f"{receiver}{separator}push_back({args})"
                if node.callee in ("len", "length", "size") and not node.args:
                    if self.inference.expression_type(node.receiver).name == "string":
                        return f"_nyx_len({receiver})"
                    return f"static_cast<int64_t>({receiver}{separator}size())"
                if node.callee == "pop" and not node.args:
                    return f"{receiver}{separator}pop_back()"
                return f"{receiver}{separator}{self._identifier(node.callee)}({args})"

            if node.callee_symbol.startswith("builtin::"):
                callee = self._BUILTIN_NAMES.get(node.callee, self._identifier(node.callee))
            else:
                callee = self._symbol(node.callee_symbol, node.callee)

            external = self.externs.get(node.callee_symbol)
            expected_arguments: List[IRType] = []
            if node.callee_symbol.startswith("type::struct::"):
                struct = self.inference.structs.get(node.callee)
                if struct is not None:
                    expected_arguments = [
                        self.inference.field_type(struct.name, field.name, field.type)
                        for field in struct.fields
                    ]
            else:
                function = self.inference.functions.get(node.callee_symbol)
                if function is not None:
                    expected_arguments = [
                        self.inference.type_of_symbol(parameter.symbol, parameter.type)
                        for parameter in function.params
                    ]
            rendered_args = []
            for index, argument in enumerate(node.args):
                argument_expected = (
                    expected_arguments[index] if index < len(expected_arguments) else None
                )
                argument_text = self._expr(argument, argument_expected)
                if external is not None and index < len(external.params):
                    parameter_type = external.params[index].type
                    if parameter_type.name == "string" and not parameter_type.pointer:
                        argument_text = f"({argument_text}).c_str()"
                rendered_args.append(argument_text)
            call = f"{callee}({', '.join(rendered_args)})"
            if node.callee_symbol.startswith("type::struct::"):
                return call
            if external is not None and external.return_type.name == "string":
                return f"std::string({call})"
            return call
        if isinstance(node, IRMemberAccess):
            member = self._identifier(node.member)
            if isinstance(node.obj, IRReference) and node.obj.symbol.startswith("foreign::cpp::"):
                return f"{self._expr(node.obj)}::{member}"
            if node.safe:
                obj = self._expr(node.obj)
                return f"_nyx_safe_member({obj}, [](const auto& _nyx_value) {{ return _nyx_value.{member}; }})"
            if isinstance(node.obj, IRReference) and node.obj.name in ("self", "this"):
                return f"this->{member}"
            return f"{self._expr(node.obj)}.{member}"
        if isinstance(node, IRIndexAccess):
            if self.inference.expression_type(node.obj).name == "string":
                return f"_nyx_string_index({self._expr(node.obj)}, {self._expr(node.index)})"
            return f"{self._expr(node.obj)}.at(static_cast<size_t>({self._expr(node.index)}))"
        if isinstance(node, IRArray):
            value_type = self.inference.expression_type(node)
            if expected is not None and expected.name == "Array" and expected.arguments:
                expected_element = expected.arguments[0]
                if not _is_known(value_type) or (
                    value_type.arguments and not _is_known(value_type.arguments[0])
                ):
                    value_type = expected
            element_type = value_type.arguments[0] if value_type.name == "Array" and value_type.arguments else ANY
            if not _is_known(element_type):
                if node.elements:
                    element_type = self.inference.expression_type(node.elements[0])
                else:
                    element_type = INT
            values = ", ".join(self._expr(element, element_type) for element in node.elements)
            return f"std::vector<{self._cpp_type(element_type, role='array')}>{{{values}}}"
        if isinstance(node, IRNullCoalesce):
            if isinstance(node.left, IRLiteral) and node.left.value is None:
                return self._expr(node.right, self.inference.expression_type(node))
            return (
                f"_nyx_coalesce({self._expr(node.left)}, [&]() {{ return {self._expr(node.right)}; }})"
            )
        if isinstance(node, IRConditional):
            result_type = expected or self.inference.expression_type(node)
            return (
                f"({self._expr(node.condition)} ? "
                f"{self._expr(node.then_expr, result_type)} : "
                f"{self._expr(node.else_expr, result_type)})"
            )
        if isinstance(node, IRMatchExpression):
            result_type = expected or self.inference.expression_type(node)
            temporary = self._temporary("match")
            rendered = self._expr(node.cases[-1].value, result_type)
            for case in reversed(node.cases[:-1]):
                rendered = (
                    f"({temporary} == {self._expr(case.pattern)} ? "
                    f"{self._expr(case.value, result_type)} : {rendered})"
                )
            return (
                f"([&](const auto& {temporary}) -> "
                f"{self._cpp_type(result_type, role='return')} {{ return {rendered}; }})"
                f"({self._expr(node.subject)})"
            )
        if isinstance(node, IRLambda):
            parameters = []
            for parameter in node.params:
                value_type = self.inference.type_of_symbol(parameter.symbol, parameter.type)
                parameters.append(
                    f"{self._cpp_type(value_type, role='parameter')} "
                    f"{self._parameter_name(parameter.symbol, parameter.name)}"
                )
            return f"[=]({', '.join(parameters)}) {{ return {self._expr(node.body)}; }}"
        raise CppEmissionError(f"Unsupported HIR expression: {type(node).__name__}")

    def _cpp_type(self, value_type: IRType, *, role: str) -> str:
        if value_type.name.startswith("foreign::cpp::"):
            native_type = value_type.name[len("foreign::cpp::"):]
            if not re.fullmatch(r"[A-Za-z_]\w*(?:::[A-Za-z_]\w*)*", native_type):
                raise CppEmissionError(f"Invalid bound C++ type '{native_type}'")
            return native_type
        if value_type.name in self.payload_enums:
            return "NyxEnumValue"
        if value_type.pointer:
            base = _strip_optional(IRType(value_type.name, value_type.arguments))
            rendered = "void" if base.name == "void" else self._cpp_type(base, role="pointer")
            return rendered + "*"
        if value_type.name == "null":
            return "std::nullptr_t"
        if value_type.optional:
            base = value_type.with_optional(False)
            if not _is_known(base):
                raise CppEmissionError(f"Cannot infer optional {role} type")
            builtin_names = {
                "void", "bool", "int", "i8", "i16", "i32", "i64", "u8", "u16", "u32", "u64",
                "int64", "int32", "float", "f32", "f64", "double",
                "string", "char", "uintptr", "size_t", "Exception", "Channel", "Array", "Iterator", "Result", "Task",
            }
            if base.name not in builtin_names and base.name not in self.declared_types:
                return "std::optional<std::monostate>"
            return f"std::optional<{self._cpp_type(base, role=role)}>"
        if value_type.is_function:
            result = self._cpp_type(value_type.return_type or VOID, role="return")
            parameters = ", ".join(
                self._cpp_type(parameter, role="parameter") for parameter in value_type.parameter_types
            )
            return f"std::function<{result}({parameters})>"
        if value_type.name == "any":
            if role in ("parameter", "variable"):
                return "auto"
            raise CppEmissionError(f"Cannot infer C++ {role} type")
        mapping = {
            "void": "void",
            "bool": "bool",
            "int": "int64_t",
            "i8": "int8_t",
            "i16": "int16_t",
            "i32": "int32_t",
            "u8": "uint8_t",
            "u16": "uint16_t",
            "u32": "uint32_t",
            "u64": "uint64_t",
            "int64": "int64_t",
            "i64": "int64_t",
            "int32": "int32_t",
            "i32": "int32_t",
            "float": "double",
            "f32": "float",
            "f64": "double",
            "double": "double",
            "string": "std::string",
            "char": "char",
            "uintptr": "uintptr_t",
            "size_t": "size_t",
            "Exception": "std::exception",
            "Channel": "_NyxChannel",
        }
        if value_type.name == "Array":
            element = value_type.arguments[0] if value_type.arguments else ANY
            if not _is_known(element):
                if role == "variable":
                    return "auto"
                raise CppEmissionError(f"Cannot infer Array element type for C++ {role}")
            return f"std::vector<{self._cpp_type(element, role='array')}>"
        if value_type.name == "Iterator":
            element = value_type.arguments[0] if value_type.arguments else ANY
            if not _is_known(element):
                raise CppEmissionError(f"Cannot infer Iterator element type for C++ {role}")
            return f"NyxIterator<{self._cpp_type(element, role='iterator')}>"
        if value_type.name == "Result":
            if len(value_type.arguments) >= 2 and all(_is_known(item) for item in value_type.arguments[:2]):
                return (
                    f"NyxResult<{self._cpp_type(value_type.arguments[0], role='result')}, "
                    f"{self._cpp_type(value_type.arguments[1], role='result')}>"
                )
            if role == "variable":
                return "auto"
            raise CppEmissionError(f"Cannot infer Result payload types for C++ {role}")
        if value_type.name == "Task":
            if len(value_type.arguments) == 1 and _is_known(value_type.arguments[0]):
                return f"NyxTask<{self._cpp_type(value_type.arguments[0], role='task')}>"
            if role == "variable":
                return "auto"
            raise CppEmissionError(f"Cannot infer Task result type for C++ {role}")
        rendered = mapping.get(value_type.name, self._identifier(value_type.name))
        if value_type.arguments:
            args = ", ".join(self._cpp_type(item, role="generic") for item in value_type.arguments)
            rendered += f"<{args}>"
        return rendered

    def _c_ffi_parameter_declaration(self, value_type: IRType, name: str) -> str:
        if value_type.is_function:
            if value_type.optional:
                raise CppEmissionError("Optional callback types are not supported by the C ABI")
            result = self._c_ffi_type(value_type.return_type or VOID)
            parameters = ", ".join(
                self._c_ffi_type(parameter) for parameter in value_type.parameter_types
            ) or "void"
            return f"{result} (*{name})({parameters})"
        return f"{self._c_ffi_type(value_type)} {name}"

    def _c_ffi_type(self, value_type: IRType) -> str:
        if value_type.is_function:
            raise CppEmissionError(
                "C ABI callback types require a named function-pointer declarator"
            )
        if value_type.pointer:
            base = IRType(value_type.name, value_type.arguments)
            rendered = "void" if base.name == "void" else self._c_ffi_type(base)
            return rendered + "*"
        mapping = {
            "any": "void*",
            "void": "void",
            "bool": "bool",
            "int": "int64_t",
            "i8": "int8_t",
            "i16": "int16_t",
            "i32": "int32_t",
            "u8": "uint8_t",
            "u16": "uint16_t",
            "u32": "uint32_t",
            "u64": "uint64_t",
            "int64": "int64_t",
            "i64": "int64_t",
            "int32": "int32_t",
            "i32": "int32_t",
            "float": "double",
            "f32": "float",
            "f64": "double",
            "double": "double",
            "string": "const char*",
            "char": "char",
            "uintptr": "uintptr_t",
            "size_t": "size_t",
        }
        return mapping.get(value_type.name, self._identifier(value_type.name))

    def _parameter_name(self, symbol: str, preferred: str) -> str:
        if symbol not in self.symbol_names:
            self.symbol_names[symbol] = self._identifier(preferred)
        return self.symbol_names[symbol]

    def _symbol(self, symbol: str, preferred: str) -> str:
        if symbol == "pattern::_":
            return "_"
        existing = self.symbol_names.get(symbol)
        if existing is not None:
            return existing
        base = self._identifier(preferred)
        if symbol.startswith("function::") and preferred in ("abs", "min", "max"):
            base = f"_nyx_user_{preferred}"
        if symbol.startswith(("builtin::", "intrinsic::", "function::", "extern::", "type::")):
            name = base
        elif "::param::" in symbol:
            name = base
        elif symbol in self.public_symbols:
            name = base
        else:
            digest = hashlib.sha256(symbol.encode("utf-8")).hexdigest()[:8]
            name = f"{base}__nyx_{digest}"
        self.symbol_names[symbol] = name
        return name

    def _temporary(self, purpose: str) -> str:
        self.counter += 1
        return f"_nyx_{purpose}_{self.counter}"

    @staticmethod
    def _identifier(name: str) -> str:
        clean = _IDENTIFIER_CHARS.sub("_", name)
        if not clean:
            clean = "_nyx_value"
        if clean[0].isdigit():
            clean = "_" + clean
        if clean in _CPP_RESERVED:
            clean += "_nyx"
        return clean

    @staticmethod
    def _string_literal(value: str) -> str:
        data = value.encode("utf-8")
        encoded = "".join(f"\\x{byte:02x}" for byte in data)
        return f"std::string(\"{encoded}\", {len(data)})"


def emit_cpp(module: IRModule) -> str:
    """Convenience entry point used by the public compiler API."""

    return HIRCppEmitter(module).emit()
