    def gen_wasm(self) -> str:
        wat_lines = [
            ";; Auto-generated by Rove (wasm - WebAssembly)",
            "(module",
            '  (import "env" "print" (func $print (param i32)))',
            '  (memory (export "memory") 1)',
        ]
