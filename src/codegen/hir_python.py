class HIRPythonEmitter:
    """Emit standalone Python 3 source from an immutable HIR module."""

    def __init__(self, module: IRModule):
        self.module = module
        self.symbol_names: Dict[str, str] = {}
        self.public_symbols = {
            item.symbol
            for item in module.items
            if isinstance(item, IRVarDecl)
        }
        self.impls: Dict[str, List[IRImpl]] = {}
        self.functions = {
            item.symbol: item for item in module.items if isinstance(item, IRFunction)
        }
        self.structs = {
            item.name: item for item in module.items if isinstance(item, IRStruct)
        }
        self.methods = {}
        self.enum_variants = {
            f"enum::{item.name}::variant::{member.name}": (item, member)
            for item in module.items if isinstance(item, IREnum)
            for member in item.members if member.is_variant
        }
        self.current_return_type: IRType | None = None
        self.counter = 0
        for item in module.items:
            if isinstance(item, IRImpl):
                self.impls.setdefault(item.target_type, []).append(item)
                for method in item.methods:
                    self.methods[(item.target_type, method.name)] = method
        self._register_declarations()

    def emit(self) -> str:
        lines = _PYTHON_RUNTIME.splitlines()
        lines.append("")
        for item in self.module.items:
            if isinstance(item, IRForeignImport):
                if item.ecosystem != "python":
                    raise PythonEmissionError(
                        f"Python target cannot consume '{item.ecosystem}' foreign import '{item.module}'"
                    )
                if not re.fullmatch(r"[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*", item.module):
                    raise PythonEmissionError(f"Invalid Python module path '{item.module}'")
                lines.append(f"import {item.module} as {self._symbol(item.symbol, item.alias)}")
        if any(isinstance(item, IRForeignImport) for item in self.module.items):
            lines.append("")

        declarations: List[IRNode] = []
        statements: List[IRStatement] = []
        for item in self.module.items:
            if isinstance(item, IRStatement):
                statements.append(item)
            elif isinstance(item, (IRImpl, IRNativeDirective, IRForeignImport)):
                continue
            else:
                declarations.append(item)

        declaration_order = (
            IRTypeAlias,
            IREnum,
            IRTrait,
            IRStruct,
            IRExternFunction,
            IRFunction,
        )
        for declaration_type in declaration_order:
            for item in declarations:
                if isinstance(item, declaration_type):
                    lines.extend(self._emit_declaration(item))
                    lines.append("")

        unknown = [
            type(item).__name__
            for item in declarations
            if not isinstance(item, declaration_order)
        ]
        if unknown:
            raise PythonEmissionError(f"Unsupported HIR declaration(s): {', '.join(unknown)}")

        if statements:
            lines.extend(self._emit_block(statements, 0))
            lines.append("")

        main = next(
            (item for item in self.module.items if isinstance(item, IRFunction) and item.name == "main"),
            None,
        )
        explicitly_called = any(
            isinstance(item, IRExprStatement)
            and isinstance(item.expr, IRCall)
            and item.expr.receiver is None
            and item.expr.callee == "main"
            for item in statements
        )
        if main is not None and not explicitly_called:
            lines.append("if __name__ == \"__main__\":")
            if main.is_async:
                lines.append(
                    f"    _rove_asyncio.run(_rove_run_task({self._symbol(main.symbol, main.name)}()))"
                )
            else:
                lines.append(f"    {self._symbol(main.symbol, main.name)}()")

        return "\n".join(lines).rstrip() + "\n"

    def _register_declarations(self) -> None:
        for item in self.module.items:
            if isinstance(
                item,
                (IRFunction, IRStruct, IRTrait, IRTypeAlias, IREnum, IRExternFunction, IRForeignImport),
            ):
                preferred = item.alias if isinstance(item, IRForeignImport) else item.name
                self.symbol_names[item.symbol] = self._identifier(preferred)
            elif isinstance(item, IRVarDecl):
                self.symbol_names[item.symbol] = self._identifier(item.name)
            if isinstance(item, IREnum):
                for member in item.members:
                    if member.is_variant:
                        self.symbol_names[f"enum::{item.name}::variant::{member.name}"] = self._identifier(member.name)

    def _emit_declaration(self, node: IRNode) -> List[str]:
        if isinstance(node, IRTypeAlias):
            return [f"{self._symbol(node.symbol, node.name)} = {self._type_name(node.actual_type)}"]
        if isinstance(node, IREnum):
            name = self._symbol(node.symbol, node.name)
            if any(member.is_variant for member in node.members):
                lines = [f"{name} = RoveEnumValue"]
                for member in node.members:
                    if not member.is_variant:
                        raise PythonEmissionError(
                            f"Payload enum '{node.name}' cannot mix discriminant member '{member.name}'"
                        )
                    params = [f"_rove_payload_{index}" for index in range(len(member.payload_types))]
                    constructor = self._symbol(
                        f"enum::{node.name}::variant::{member.name}", member.name
                    )
                    lines.extend((
                        f"def {constructor}({', '.join(params)}):",
                        f"    return RoveEnumValue({node.name!r}, {member.name!r}, [{', '.join(params)}])",
                    ))
                return lines
            lines = [f"class {name}:"]
            if not node.members:
                lines.append("    pass")
            for member in node.members:
                value = self._expr(member.value) if member.value is not None else repr(member.name)
                lines.append(f"    {self._identifier(member.name)} = {value}")
            return lines
        if isinstance(node, IRTrait):
            lines = [f"class {self._symbol(node.symbol, node.name)}:"]
            if not node.methods:
                lines.append("    pass")
            for method in node.methods:
                lines.extend(self._emit_function(method, 1, method=True, abstract=True))
            return lines
        if isinstance(node, IRStruct):
            return self._emit_struct(node)
        if isinstance(node, IRExternFunction):
            parameters = [self._parameter_name(param.symbol, param.name) for param in node.params]
            if node.varargs:
                parameters.append("*_rove_varargs")
            lines = [f"def {self._symbol(node.symbol, node.name)}({', '.join(parameters)}):"]
            lines.append(
                f"    raise RuntimeError({repr(f'extern {node.abi} function {node.name} is unavailable on python')})"
            )
            return lines
        if isinstance(node, IRFunction):
            return self._emit_function(node, 0)
        raise PythonEmissionError(f"Unsupported HIR declaration: {type(node).__name__}")

    def _emit_struct(self, node: IRStruct) -> List[str]:
        name = self._symbol(node.symbol, node.name)
        lines = [f"class {name}:"]
        fields = []
        for field in node.fields:
            field_name = self._identifier(field.name)
            if field.default is None:
                fields.append(field_name)
            else:
                fields.append(f"{field_name}={self._expr_as(field.default, field.type)}")
        methods = [method for impl in self.impls.get(node.name, ()) for method in impl.methods]
        if fields:
            lines.append(f"    def __init__(self, {', '.join(fields)}):")
            for field in node.fields:
                field_name = self._identifier(field.name)
                lines.append(f"        self.{field_name} = {field_name}")
        elif not methods:
            lines.append("    pass")
        else:
            lines.append("    def __init__(self):")
            lines.append("        pass")
        for method in methods:
            lines.extend(self._emit_function(method, 1, method=True))
        return lines

    def _emit_function(
        self,
        node: IRFunction,
        indent: int,
        *,
        method: bool = False,
        abstract: bool = False,
    ) -> List[str]:
        prefix = "    " * indent
        parameters: List[str] = []
        plain_parameters: List[str] = []
        call_arguments: List[str] = []
        for index, parameter in enumerate(node.params):
            if method and index == 0 and parameter.name in ("self", "this"):
                name = "self"
                self.symbol_names[parameter.symbol] = name
            else:
                name = self._parameter_name(parameter.symbol, parameter.name)
            plain_parameters.append(name)
            if not (method and index == 0 and parameter.name in ("self", "this")):
                call_arguments.append(name)
            if parameter.default is not None:
                name += f"={self._expr_as(parameter.default, parameter.type)}"
            parameters.append(name)
        public_name = self._identifier(node.name)
        if node.is_async:
            implementation_name = f"_rove_async_impl_{public_name}"
            lines = [
                f"{prefix}async def {implementation_name}({', '.join(plain_parameters)}):"
            ]
        else:
            lines = [f"{prefix}def {public_name}({', '.join(parameters)}):"]
        if node.doc_comment:
            lines.append(f"{prefix}    {repr(node.doc_comment)}")
        previous_return = self.current_return_type
        self.current_return_type = node.return_type
        try:
            if abstract:
                lines.append(f"{prefix}    raise NotImplementedError({repr(node.name)})")
            elif node.return_type.name == "Result" and len(node.return_type.arguments) == 2:
                caught = self._temporary("propagated")
                lines.append(f"{prefix}    try:")
                lines.extend(self._emit_block(node.body, indent + 2))
                lines.append(f"{prefix}    except _RoveResultPropagation as {caught}:")
                lines.append(f"{prefix}        return Err({caught}.error)")
            else:
                lines.extend(self._emit_block(node.body, indent + 1))
        finally:
            self.current_return_type = previous_return
        if node.is_async:
            lines.append(f"{prefix}def {public_name}({', '.join(parameters)}):")
            if node.doc_comment:
                lines.append(f"{prefix}    {repr(node.doc_comment)}")
            callee = f"self.{implementation_name}" if method else implementation_name
            lines.append(
                f"{prefix}    return _RoveTask({callee}({', '.join(call_arguments)}))"
            )
        return lines

    def _emit_block(self, statements: Sequence[IRStatement], indent: int) -> List[str]:
        prefix = "    " * indent
        if not statements:
            return [f"{prefix}pass"]
        if any(isinstance(statement, IRDefer) for statement in statements):
            scope = self._temporary("defer")
            lines = [f"{prefix}with _RoveDeferScope() as {scope}:"]
            for statement in statements:
                if isinstance(statement, IRDefer):
                    lines.append(f"{prefix}    {scope}.push(lambda: {self._expr(statement.expr)})")
                else:
                    lines.extend(self._emit_statement(statement, indent + 1))
            return lines
        lines: List[str] = []
        for statement in statements:
            lines.extend(self._emit_statement(statement, indent))
        return lines or [f"{prefix}pass"]

    def _condition(self, node: IRExpr) -> str:
        rendered = self._expr(node)
        return f"_rove_require_bool({rendered})" if node.type.is_unknown else rendered

    def _emit_statement(self, node: IRStatement, indent: int) -> List[str]:
        prefix = "    " * indent
        if isinstance(node, IRVarDecl):
            name = self._symbol(node.symbol, node.name)
            value = self._copy_value(self._expr_as(node.expr, node.type), node.type)
            return [f"{prefix}{name} = {value}"]
        if isinstance(node, IRAssign):
            value = self._copy_value(self._expr_as(node.expr, node.target.type), node.target.type)
            return [
                f"{prefix}{self._expr(node.target)} = {value}"
            ]
        if isinstance(node, IRExprStatement):
            return [f"{prefix}{self._expr(node.expr)}"]
        if isinstance(node, IRReturn):
            return [
                f"{prefix}return"
                if node.expr is None
                else f"{prefix}return {self._expr_as(node.expr, self.current_return_type)}"
            ]
        if isinstance(node, IRThrow):
            return [f"{prefix}raise RuntimeError(to_string({self._expr(node.expr)}))"]
        if isinstance(node, IRYield):
            return [f"{prefix}yield {self._expr(node.expr)}"]
        if isinstance(node, IRIf):
            lines = [f"{prefix}if {self._condition(node.condition)}:"]
            lines.extend(self._emit_block(node.then_branch, indent + 1))
            for condition, body in node.elif_branches:
                lines.append(f"{prefix}elif {self._condition(condition)}:")
                lines.extend(self._emit_block(body, indent + 1))
            if node.else_branch is not None:
                lines.append(f"{prefix}else:")
                lines.extend(self._emit_block(node.else_branch, indent + 1))
            return lines
        if isinstance(node, IRWhile):
            lines = [f"{prefix}while {self._condition(node.condition)}:"]
            lines.extend(self._emit_block(node.body, indent + 1))
            return lines
        if isinstance(node, IRFor):
            variable = self._symbol(node.symbol, node.var_name)
            if node.collection_expr is not None:
                iterator = self._expr(node.collection_expr)
            elif node.start_expr is not None and node.end_expr is not None:
                iterator = f"range({self._expr(node.start_expr)}, {self._expr(node.end_expr)} + 1)"
            else:
                raise PythonEmissionError("HIR for-loop has neither a collection nor a range")
            lines = [f"{prefix}for {variable} in {iterator}:"]
            lines.extend(self._emit_block(node.body, indent + 1))
            return lines
        if isinstance(node, IRBreak):
            return [f"{prefix}break"]
        if isinstance(node, IRContinue):
            return [f"{prefix}continue"]
        if isinstance(node, IRDefer):
            raise PythonEmissionError("defer must be emitted by its lexical block")
        if isinstance(node, IRGuard):
            lines = [f"{prefix}if not ({self._condition(node.condition)}):"]
            lines.extend(self._emit_block(node.else_body, indent + 1))
            return lines
        if isinstance(node, IRUnsafeBlock):
            lines = [f"{prefix}# unsafe boundary"]
            lines.extend(self._emit_block(node.body, indent))
            return lines
        if isinstance(node, IRSpawn):
            worker = self._temporary("spawn")
            lines = [f"{prefix}def {worker}():"]
            lines.extend(self._emit_block(node.body, indent + 1))
            lines.append(f"{prefix}_rove_threading.Thread(target={worker}, daemon=True).start()")
            return lines
        if isinstance(node, IRAssert):
            suffix = "" if node.message is None else f", {node.message!r}"
            return [f"{prefix}assert {self._condition(node.condition)}{suffix}"]
        if isinstance(node, IRMatch):
            return self._emit_match(node, indent)
        if isinstance(node, IRTryCatch):
            error_name = self._symbol(node.error_symbol, node.error_name)
            caught_name = self._temporary("caught")
            lines = [f"{prefix}try:"]
            lines.extend(self._emit_block(node.try_body, indent + 1))
            lines.append(f"{prefix}except Exception as {caught_name}:")
            lines.append(f"{prefix}    {error_name} = str({caught_name})")
            lines.extend(self._emit_block(node.catch_body, indent + 1))
            return lines
        if isinstance(node, IRTestBlock):
            lines = [f"{prefix}# test: {node.description}"]
            lines.extend(self._emit_block(node.body, indent))
            return lines
        raise PythonEmissionError(f"Unsupported HIR statement: {type(node).__name__}")

    def _emit_match(self, node: IRMatch, indent: int) -> List[str]:
        prefix = "    " * indent
        value = self._temporary("match")
        lines = [f"{prefix}{value} = {self._expr(node.expr)}"]
        emitted_condition = False
        for case in node.cases:
            pattern = case.pattern
            wildcard = (
                isinstance(pattern, IRReference) and pattern.name == "_"
            ) or (
                isinstance(pattern, IRLiteral) and pattern.value == "_"
            )
            binding = isinstance(pattern, IRReference) and pattern.name != "_"
            payload = None
            variant = self.enum_variants.get(pattern.callee_symbol) if isinstance(pattern, IRCall) else None
            payload_bindings = []
            if variant is not None:
                enum_node, member = variant
                condition = (
                    f"isinstance({value}, RoveEnumValue) and "
                    f"{value}.enum_name == {enum_node.name!r} and "
                    f"{value}.variant_name == {member.name!r}"
                )
                for index, argument in enumerate(pattern.args):
                    if isinstance(argument, IRReference) and argument.name != "_":
                        payload_bindings.append(
                            f"{prefix}    {self._symbol(argument.symbol, argument.name)} = "
                            f"{value}.payload[{index}]"
                        )
            elif isinstance(pattern, IRCall) and pattern.callee in ("Ok", "Err"):
                expected = "True" if pattern.callee == "Ok" else "False"
                condition = f"isinstance({value}, Result) and {value}.is_ok is {expected}"
                if pattern.args and isinstance(pattern.args[0], IRReference):
                    payload = self._symbol(pattern.args[0].symbol, pattern.args[0].name)
            elif wildcard or binding:
                condition = "True"
            elif isinstance(pattern, IRCall):
                raise PythonEmissionError(
                    f"Unsupported constructor pattern '{pattern.callee}' on python"
                )
            else:
                condition = f"{value} == {self._expr(pattern)}"

            if (wildcard or binding) and emitted_condition:
                lines.append(f"{prefix}else:")
            else:
                keyword_text = "if" if not emitted_condition else "elif"
                lines.append(f"{prefix}{keyword_text} {condition}:")
            if binding:
                binding_name = self._symbol(pattern.symbol, pattern.name)
                lines.append(f"{prefix}    {binding_name} = {value}")
            if payload is not None:
                lines.append(f"{prefix}    {payload} = {value}.value")
            lines.extend(payload_bindings)
            lines.extend(self._emit_block(case.body, indent + 1))
            emitted_condition = True
            if wildcard or binding:
                break
        return lines

    def _expr(self, node: IRExpr | None) -> str:
        if node is None:
            raise PythonEmissionError("Missing HIR expression")
        if isinstance(node, IRLiteral):
            if node.value is None:
                return "None"
            if isinstance(node.value, bool):
                return "True" if node.value else "False"
            if node.type.name == "int" and isinstance(node.value, int):
                return f"_rove_i64({node.value!r})"
            return repr(node.value)
        if isinstance(node, IRReference):
            return self._symbol(node.symbol, node.name)
        if isinstance(node, IRBinary):
            comparison = node.op in ("==", "!=", "<", "<=", ">", ">=")
            promote_to_float = node.type.name == "float" or (
                comparison and (node.left.type.name == "float" or node.right.type.name == "float")
            )
            expected = FLOAT if promote_to_float else None
            left = self._expr_as(node.left, expected)
            right = self._expr_as(node.right, expected)
            integer_operators = {
                "+": "_rove_i64_add",
                "-": "_rove_i64_sub",
                "*": "_rove_i64_mul",
                "/": "_rove_int_div",
                "%": "_rove_int_mod",
                "&": "_rove_i64_and",
                "^": "_rove_i64_xor",
                "|": "_rove_i64_or",
                "<<": "_rove_i64_shl",
                ">>": "_rove_i64_shr",
            }
            if node.type.name == "int" and node.op in integer_operators:
                return f"{integer_operators[node.op]}({left}, {right})"
            if node.type.name == "float" and node.op == "/":
                return f"_rove_f64_div({left}, {right})"
            if node.type.name == "float" and node.op == "%":
                return f"_rove_f64_mod({left}, {right})"
            operator = {"&&": "and", "||": "or"}.get(node.op, node.op)
            return f"({left} {operator} {right})"
        if isinstance(node, IRUnary):
            operator = "not " if node.op in ("!", "not") else node.op
            if node.type.name == "int":
                if node.op == "-":
                    return f"_rove_i64_neg({self._expr(node.expr)})"
                if node.op == "~":
                    return f"_rove_i64_not({self._expr(node.expr)})"
                if node.op == "+":
                    return self._expr(node.expr)
            operand = self._expr_as(node.expr, FLOAT if node.type.name == "float" else None)
            return f"({operator}{operand})"
        if isinstance(node, IRAwait):
            return f"(await {self._expr(node.expr)})"
        if isinstance(node, IRResultPropagate):
            return f"_rove_propagate({self._expr(node.expr)})"
        if isinstance(node, IRCall):
            expected_types = self._call_parameter_types(node)
            args = ", ".join(
                self._copy_value(
                    self._expr_as(
                        argument,
                        expected_types[index] if index < len(expected_types) else None,
                    ),
                    expected_types[index] if index < len(expected_types) else argument.type,
                )
                for index, argument in enumerate(node.args)
            )
            if node.receiver is not None:
                receiver = self._expr(node.receiver)
                if node.callee == "push":
                    return f"{receiver}.append({args})"
                if not node.args and (
                    node.callee == "len" or (
                        node.callee in ("length", "size")
                        and node.receiver.type.name in ("string", "Array")
                    )
                ):
                    return f"_rove_i64(len({receiver}))"
                return f"{receiver}.{self._identifier(node.callee)}({args})"
            collection_builtins = {
                "map": "_rove_map",
                "filter": "_rove_filter",
                "fold": "_rove_fold",
            }
            if node.callee_symbol.startswith("builtin::") and node.callee in collection_builtins:
                callee = collection_builtins[node.callee]
            else:
                callee = self._symbol(node.callee_symbol, node.callee)
            if node.callee_symbol == "builtin::len":
                return f"_rove_i64(len({args}))"
            return f"{callee}({args})"
        if isinstance(node, IRMemberAccess):
            obj = self._expr(node.obj)
            member = self._identifier(node.member)
            if node.safe:
                return f"_rove_safe_getattr({obj}, {member!r})"
            return f"{obj}.{member}"
        if isinstance(node, IRIndexAccess):
            if node.obj.type.name == "string":
                return f"_rove_string_index({self._expr(node.obj)}, {self._expr(node.index)})"
            return f"{self._expr(node.obj)}[{self._expr(node.index)}]"
        if isinstance(node, IRArray):
            element_type = node.type.arguments[0] if node.type.arguments else None
            return "[" + ", ".join(
                self._expr_as(element, element_type) for element in node.elements
            ) + "]"
        if isinstance(node, IRNullCoalesce):
            return f"_rove_coalesce({self._expr(node.left)}, lambda: {self._expr(node.right)})"
        if isinstance(node, IRConditional):
            return (
                f"({self._expr_as(node.then_expr, node.type)} if "
                f"{self._condition(node.condition)} else "
                f"{self._expr_as(node.else_expr, node.type)})"
            )
        if isinstance(node, IRMatchExpression):
            temporary = self._temporary("match")
            rendered = self._expr_as(node.cases[-1].value, node.type)
            for case in reversed(node.cases[:-1]):
                rendered = (
                    f"({self._expr_as(case.value, node.type)} if "
                    f"{temporary} == {self._expr(case.pattern)} else {rendered})"
                )
            return f"(lambda {temporary}: {rendered})({self._expr(node.subject)})"
        if isinstance(node, IRLambda):
            parameters = [self._parameter_name(param.symbol, param.name) for param in node.params]
            return f"(lambda {', '.join(parameters)}: {self._expr(node.body)})"
        raise PythonEmissionError(f"Unsupported HIR expression: {type(node).__name__}")

    def _expr_as(self, node: IRExpr, expected: IRType | None) -> str:
        rendered = self._expr(node)
        if expected is not None and expected.name == "float" and node.type.name == "int":
            return f"float({rendered})"
        return rendered

    def _copy_value(self, rendered: str, value_type: IRType | None) -> str:
        if value_type is None:
            return rendered
        if value_type.name == "Array" or value_type.name in self.structs:
            return f"_rove_clone_value({rendered})"
        if value_type.name in ("Option", "Result") and any(
            argument.name == "Array" or argument.name in self.structs
            for argument in value_type.arguments
        ):
            return f"_rove_clone_value({rendered})"
        return rendered

    def _call_parameter_types(self, node: IRCall) -> Sequence[IRType]:
        if node.receiver is not None:
            method = self.methods.get((node.receiver.type.name, node.callee))
            if method is None:
                return ()
            parameters = list(method.params)
            if parameters and parameters[0].name in ("self", "this"):
                parameters = parameters[1:]
            return tuple(parameter.type for parameter in parameters)

        if node.callee_symbol.startswith("type::struct::"):
            struct = self.structs.get(node.callee)
            return tuple(field.type for field in struct.fields) if struct is not None else ()

        function = self.functions.get(node.callee_symbol)
        if function is not None:
            return tuple(parameter.type for parameter in function.params)
        signature = BUILTINS.get(node.callee) or INTRINSICS.get(node.callee)
        return signature.parameters if signature is not None else ()

    def _parameter_name(self, symbol: str, preferred: str) -> str:
        if symbol not in self.symbol_names:
            self.symbol_names[symbol] = self._identifier(preferred)
        return self.symbol_names[symbol]

    def _symbol(self, symbol: str, preferred: str) -> str:
        existing = self.symbol_names.get(symbol)
        if existing is not None:
            return existing
        base = self._identifier(preferred)
        if symbol.startswith(("builtin::", "intrinsic::", "function::", "extern::", "type::")):
            name = base
        elif "::param::" in symbol:
            name = base
        elif symbol in self.public_symbols:
            name = base
        elif symbol == "pattern::_":
            name = "_"
        else:
            digest = hashlib.sha256(symbol.encode("utf-8")).hexdigest()[:8]
            name = f"{base}__rove_{digest}"
        self.symbol_names[symbol] = name
        return name

    def _temporary(self, purpose: str) -> str:
        self.counter += 1
        return f"_rove_{purpose}_{self.counter}"

    @staticmethod
    def _identifier(name: str) -> str:
        clean = _IDENTIFIER_CHARS.sub("_", name)
        if not clean:
            clean = "_rove_value"
        if clean[0].isdigit():
            clean = "_" + clean
        if keyword.iskeyword(clean):
            clean += "_rove"
        return clean

    def _type_name(self, value_type: IRType) -> str:
        mapping = {
            "any": "object",
            "void": "type(None)",
            "bool": "bool",
            "int": "int",
            "float": "float",
            "string": "str",
            "Array": "list",
        }
        return mapping.get(value_type.name, self._identifier(value_type.name))


def emit_python(module: IRModule) -> str:
    """Convenience entry point used by the public compiler API."""

    return HIRPythonEmitter(module).emit()
