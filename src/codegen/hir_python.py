def _rove_normalize_decimal(text):
    text = text.lower()
    if text in ("nan", "inf", "-inf"):
        return text
    negative = text.startswith("-")
    if text[:1] in ("+", "-"):
        text = text[1:]
    mantissa, marker, exponent_text = text.partition("e")
    exponent = int(exponent_text) if marker else 0
    dot = mantissa.find(".")
    decimal_position = (len(mantissa) if dot < 0 else dot) + exponent
    digits = mantissa.replace(".", "")
    first = 0
    while first < len(digits) and digits[first] == "0":
        first += 1
    if first == len(digits):
        return "0"
    decimal_position -= first
    digits = digits[first:].rstrip("0") or "0"
    if -6 < decimal_position <= 21:
        if decimal_position <= 0:
            result = "0." + ("0" * -decimal_position) + digits
        elif decimal_position >= len(digits):
            result = digits + ("0" * (decimal_position - len(digits)))
        else:
            result = digits[:decimal_position] + "." + digits[decimal_position:]
    else:
        result = digits[0]
        if len(digits) > 1:
            result += "." + digits[1:]
        scientific_exponent = decimal_position - 1
        result += "e" + ("+" if scientific_exponent >= 0 else "") + str(scientific_exponent)
    return ("-" if negative else "") + result


